8. חניון תיאורטי
בשלב השלד לא נזכיר תיאורטיקנים בגוף המאמר, אבל יש כמה כיוונים שכדאי לבדוק בהמשך כדי לעגן את הטיעון:
•  בושה כרגש חברתי וכרגש של עצמי-בעיני-האחר; ההבדל בין shame לבין guilt והקשר בין בושה לבין הערכה גלובלית של העצמי.
•  Social rank / status: הקשר בין בושה, ירידה במעמד, איום חברתי והתנהגות של כניעה או הסתתרות.
•  Observational learning / vicarious learning: כיצד צפייה בתוצאה של פעולה אצל אדם אחר מלמדת אותי מה כדאי לי לעשות או לא לעשות.
•  Norm enforcement: הדרך שבה קבוצה אוכפת נורמות באמצעות תגובות חברתיות ולא רק באמצעות חוקים רשמיים.
•  Ostracism / exclusion: הקשר בין איום בהדרה לבין קונפורמיות והתאמת התנהגות.
•  Avoidance as control: הימנעות כאסטרטגיה שמקטינה אי-ודאות ומגדילה תחושת שליטה.
•  Transmission of aggression / bullying scripts: כיצד צפייה בביוש יכולה ללמד גם את דרכי הפעלת הכוח, לא רק את הדרכים להימנע ממנו.
•  הבחנה אפשרית בין בושה שנולדת ממראה "עשית משהו לא מתאים" לבין בושה עמוקה יותר שבה המראה מחזירה "אתה עצמך לא מתאים".
כל אלה הם חניון בלבד. המאמר עצמו צריך להישאר נגיש, חי ומבני: מראה מביישת, קבוצה, מעמד, פחד, למידה, הימנעות.
