תפקיד המאמר בתוך רצף התיאוריה
מאמר 5 עסק במראות: תגובות הסביבה אל הילד נעשות מראות שדרכן הוא לומד משהו על עצמו. מאמר 6 התמקד במראה המביישת ובכוחה של בושה — לא רק ברגע ההשפלה עצמו, אלא גם בפחד מפניה, בלמידה מכלי ראשון ומכלי שני ובהימנעות שנבנית סביבה.
מאמר 7 אינו עוד מאמר על בושה. הוא חוזר צעד אחד אחורה ושואל שאלה בסיסית יותר: מה קורה לילד שחלקים גדולים מחייו מתרחשים לעיני אחרים — גם כאשר איש אינו צוחק, מבייש או מגיב? מה עושה עצם הנוכחות המתמשכת של המבט? ומה חסר כאשר כמעט אין מרחב שבו אפשר פשוט להיות בלי להיראות?
נראות עונה לצורך שמישהו יראה אותי. פרטיות מגינה על הזכות שלא יראו לי הכול.
זהו משפט היסוד של המאמר. הוא מחזיק את ההבחנה בין שני צרכים שנראים לכאורה מנוגדים אך שניהם חיוניים: הצורך להיות נראה, והזכות להיות לא־נראה; הצורך שמישהו יקלוט אותי, והצורך שיהיו בי חלקים שלא כולם יכולים לראות; הצורך בקשר, והצורך במרחב פנימי.
אבן דומינו 1 — ״רואים אותי״ ו״רואים לי״ אינם אותו דבר
״רואים אותי״ יכול לתאר חוויה עמוקה וטובה: מישהו מבחין בי, קולט אותי, מכיר אותי, רואה משהו מן הסיפור שמאחורי ההתנהגות. זה היה לבו של מאמר הנראות.
״רואים לי״ מתחיל במקום אחר. רואים משהו שלא רציתי שיראו. משהו שהייתי מעדיפה להסתיר, לשמור לעצמי, לבחור אם ומתי לחשוף.
• רואים לי שאני מפחדת.
• רואים לי שבכיתי.
• רואים לי את הגוף.
• רואים לי שהרטבתי.
• רואים לי שלא בחרו בי.
• רואים לי שאמא לא באה.
• רואים לי שקינאתי.
• רואים לי שאני לא יודעת.
• רואים לי שנפגעתי.
• רואים לי שאני רוצה יותר.
ה״לי״ הוא כל הסיפור. הוא מסמן בעלות: יש כאן משהו שאני חווה כשייך לי, אבל הוא נעשה נגיש למבטו של האחר בלי שבחרתי בכך.
״רואים לי״ מתחיל במקום שבו משהו שאני חווה כשייך לי נעשה נגיש למבטו של האחר בלי שבחרתי בכך.
להיות נראה ולהיות חשוף אינם אותו הדבר.
מכאן פרטיות מקבלת משמעות התפתחותית רחבה הרבה יותר מסוד, דלת או מגירה. היא קשורה למידה שבה יש לי שליטה על מה מן העצמי שלי נמצא בשדה הראייה של האחר.
אבן דומינו 2 — שתי נקודות תצפית על העצמי: גוף ראשון וגוף שלישי
המבט בגוף ראשון — אני חווה את עצמי מתוכי
בפרספקטיבה הפנימית אני רואה וחווה את עצמי מתוך המקום שבו אני נמצאת בתוכי. השאלות הן: מה אני רוצה? מה אני מרגישה? מה נעים לי? מה מפחיד אותי? מה מעניין אותי? מה אני מדמיינת? מה יפה בעיניי? מה נכון לי?
הפרספקטיבה הזאת אינה נשענת בראש ובראשונה על השוואה. אני לא צריכה לדעת אם אחרים מפחדים יותר או פחות כדי לדעת שאני מפחדת. אני לא צריכה לדעת אם האחר אוהב את הדבר כדי לדעת שהוא מוצא חן בעיניי. אני לא צריכה דירוג כדי לדעת שמשהו מכאיב לי, מסקרן אותי או מושך אותי.
המבט מבפנים שואל: ״מה קורה לי?״
המבט בגוף שלישי — אני רואה את עצמי כאילו מבחוץ
כאן אני שואלת: איך אני נראית? איך ההתנהגות הזאת נראית מן הצד? איך אני ביחס לאחרים? מה הם יחשבו? האם אני יותר או פחות? האם זה מקובל? יפה? מביך? חלש? חריג?
הפרספקטיבה החיצונית מכניסה בהכרח מערכות מדידה שאינן רק שלי: סולם הערכים של האחרים, ההעדפות שלהם, הנורמות שלהם, האג׳נדות שלהם, וההשוואה ביני לבין אחרים. זהו השוני המהותי בין שתי אופנויות ההתבוננות.
המבט מבחוץ שואל: ״איך הדבר שקורה לי נראה ונמדד בעיני אחרים?״
אבן דומינו 3 — המבט מבחוץ נחוץ; הסדר ההתפתחותי הוא שקובע
המבט מבחוץ אינו אויב. הוא מוסיף מידע שהפרספקטיבה בגוף ראשון אינה יכולה לתת. אני יכולה לחשוב שאני מדברת בנחת ולא לדעת שאני צועקת. אני יכולה לא להבין שהמשחק שלי דוחק ילד אחר החוצה. אני יכולה לחשוב שהבדיחה מצחיקה ולא לקלוט שהיא פוגעת. היכולת לראות את עצמי מבחוץ מאפשרת מודעות עצמית, אמפתיה, התחשבות, תיקון, חיים חברתיים וראיית עצמי בהקשר.
אבל מבחינה התפתחותית הסדר חשוב. הילד קודם חי את עצמו מבפנים, ורק בהדרגה לומד גם להסתכל על עצמו חי. לפרספקטיבה הפנימית אמור להיות מעין פור התפתחותי: זמן, חזרתיות וביטחון שבהם החוויה הפנימית נעשית נקודת מוצא מוכרת ואמינה. לאחר מכן הפרספקטיבה החיצונית יכולה להתווסף, להרחיב, לתקן ולהעשיר — בלי למחוק את הראשונה.
היכולת לראות את עצמי מבחוץ אמורה להתווסף למבט מבפנים — לא להחליף אותו.
כשהמבט מבחוץ מתווסף במידה הנכונה, הוא משיג את המבט מבפנים ומרחיב אותו. כשהוא מגיע מוקדם מדי ובעוצמה גדולה מדי, הוא עלול להשיג אותו — ואז להסיג אותו.
זהו ציר של מידה ותזמון, לא טענה נגד מודעות חברתית. הבעיה אינה שהילד לומד לראות את עצמו דרך האחר; הוא מוכרח ללמוד זאת. השאלה היא האם הפרספקטיבה הנוספת מגיעה אל עצמי שכבר קיבל מספיק מקום להתהוות מבפנים.
אבן דומינו 4 — פרטיות היא האפשרות להפסיק להיות נצפה
אנחנו רגילים לחשוב על פרטיות במונחים של מבוגרים: חדר, דלת, סוד, חפצים אישיים. אבל מבחינה התפתחותית פרטיות היא דבר ראשוני יותר. היא מצב שבו איני נדרש להתנהל מול האפשרות שמישהו רואה אותי.
פרטיות אינה רק האפשרות להסתיר מידע. היא האפשרות לחיות לרגע בלי להיות נצפה.
אחת מצורות החופש הבסיסיות ביותר היא האפשרות להפסיק להיות אובייקט למבטו של מישהו אחר.
כאן נמצא גם החניון המטפורי של ״האח הגדול״. בית הילדים כמובן אינו מערכת פיקוח מכוונת ואין כאן טענה שאנשים ישבו וצפו בילדים. אבל יש עיקרון שראוי לבדוק: עצם הידיעה שאני עשוי להיראות משנה את ההתנהגות שלי גם כשאף אחד אינו מסתכל בי בפועל. כשהאפשרות להיות נצפה כמעט תמידית, המבט נעשה חלק מן השדה שבתוכו אני חי.
אבן דומינו 5 — מה מתפתח כשאף אחד לא מסתכל?
כאן המאמר צריך לעצור ולשאול שאלה שנוטים כמעט לא לשאול: מה בעצם קורה לאדם כשהוא לבד, או כשהוא עם עצמו בתוך נוכחות בטוחה שאינה פולשת? אילו תהליכים צריכים מרחב שאינו נצפה?
• חלימה בהקיץ — עולם פנימי שאינו צריך להיות מובן או מוסבר לאיש.
• דמיון — האפשרות להמציא תרחישים, זהויות, משחקים ומחשבות בלי שמישהו ידרג אותם.
• שעמום — זמן שבו אף אחד אינו מספק גירוי מבחוץ, ומתוך הריק מתחיל להופיע מה אני רוצה לעשות.
• משחק פרטי — משחק שאינו צריך להיות מובן, מקובל או מוצלח בעיני איש.
• שיחה פנימית — לנסות מחשבה, לשנות אותה, לסגת ממנה, בלי להתחייב לה מול קהל.
• רגש לא־מנוהל חברתית — לבכות בלי לראות איך אני נראית כשאני בוכה; לכעוס בלי לעקוב מיד אחר תגובות הפנים סביבי.
• העדפה — לגלות מה אני אוהבת לפני שאני יודעת מה האחרים אוהבים.
• יוזמה — משהו מתחיל בי, ולא כתגובה למה שכבר נמצא סביבי.
כשאף אחד אינו מסתכל, יש הזדמנות לגלות מה מופיע בי לפני שאני בודק כיצד הוא מתקבל בחוץ.
אין כאן טענה שכל התהליכים האלה אינם יכולים להתרחש בנוכחות אחרים. ילדים חולמים בהקיץ גם בקבוצה, מדמיינים גם בחדר מלא ילדים וחושבים מחשבות פרטיות גם כשכולם מסביב. השאלה המדויקת יותר היא מה קורה לאיכות ולחופש של התהליכים האלה כאשר האפשרות להיות לא־נצפה מצומצמת מאוד.
אבן דומינו 6 — להיות לבד אינו להיות בודד
צריך לעשות כאן סדר בין מושגים שנוטים להתערבב.
להיות לבד
מצב שבו איני כרגע באינטראקציה עם אחרים, או שיש לי מרחב פסיכולוגי שאינו מוחזק בידי המבט שלהם. הוא יכול להיות נעים, בטוח, מלא, יצירתי ומאפשר.
בדידות
חוויה של חסר בקשר: אני רוצה קרבה, נוכחות או שייכות ואיני מקבל אותן. אפשר להיות לבד בלי להיות בודד, ואפשר להיות מוקף בעשרים ילדים ולהרגיש בודד מאוד.
להיות לבד בנוכחות אדם אחר
זהו מצב התפתחותי עדין וחשוב במיוחד: המבוגר נמצא, זמין, מגן ואפשר לפנות אליו, אבל הוא אינו דורש אינטראקציה ואינו מפרש כל תנועה. הילד יכול לשחק, לחלום, לחשוב ולהיות עם עצמו כשהקשר הבטוח קיים ברקע.
הילד יכול להיות מוחזק בלי להיות מוחזק תחת מבט.
ההפך מ״לבד״ אינו בהכרח ״ביחד״. ההפך ממרחב פנימי הוא לפעמים ״תחת מבט״.
מכאן פרטיות אינה מחייבת בידוד. הצורך אינו בהכרח שאיש לא יהיה בסביבה, אלא שלא אהיה כל הזמן אובייקט של הסביבה. אפשר להיות באותו חדר ולהחזיק עולם פרטי. השאלה איננה רק כמה שעות הילד היה פיזית לבדו, אלא כמה זמן היה לו שבו לא נדרש להיות מודע לכך שהוא נראה.
אבן דומינו 7 — בבית הילדים כמעט לא היה ״מחוץ למבט״
כאן נכנסת המציאות המבנית של בית הילדים. הקבוצה נמצאת בקימה, בהתלבשות, באוכל, במשחק, במריבה, בבכי, במקלחת, בחולי, בהשכבה, בשינה ובהתעוררות. גם כשהילד רוצה להתכנס, עצם ההתכנסות יכולה להיראות. גם כשהמחשבה פרטית, הגוף שמחזיק אותה חי בתוך שטח ציבורי מאוד של הקבוצה.
חשוב לדייק: גם המבוגרים ראו לילדים. מטפלות, מורים והורים היו חלק ממערך המבטים. ״רואים לי״ אינו שייך רק לילדים. אבל למבט של הילדים הייתה משמעות מיוחדת משום שילדי הקבוצה היו אלה שבתוכם הילד נדרש לחיות את מעמדו החברתי יום אחר יום.
הילד אינו רק חי את מה שקורה לו; כמעט בו־זמנית הוא חי גם את העובדה שזה נראה.
אין כאן טענה שלא היו מחשבות פרטיות, פנטזיה, חלימה או עולם פנימי. ודאי שהיו. השאלה היא מה קורה להתפתחותו של עולם פנימי כאשר הוא נבנה בסביבה שבה האפשרות להיות לא־נצפה מצומצמת מאוד.
אבן דומינו 8 — למה דווקא המבט של הילדים חשוב כל כך? כי הוא קשור למעמד, כוח ומוגנות
בקבוצת ילדים, המעמד של היחיד אינו פרט קוסמטי. הוא קובע משהו מן הכוח שיש לו בתוך הקבוצה: מי נחשב, מי משפיע, מי יכול להתנגד, מי יכול להרשות לעצמו להיות חריג, מי מצחיק ומי זה שצוחקים עליו, מי נעשה מטרה ומי מוגן יותר מפני הפיכתו למטרה.
כוח חברתי הוא גם סוג של מוגנות. ככל שיש לילד יותר כוח ומעמד, הוא עשוי להיות מוגן יותר מפני לעג, ביטול, הדרה, התעלמות, העלמה או פגיעה. ככל שמעמדו חלש יותר, המבט של האחרים יכול להיות מסוכן יותר.
״רואים לי״ אינו רק איום על פרטיות. בקבוצת ילדים הוא יכול להיות גם איום על המעמד — ולכן על מידת המוגנות שלי בתוך הקבוצה.
זה מסביר מדוע המבט כל כך חשוב. המידע שנחשף אינו רק מידע. בתוך קבוצה אפשר לעשות בו שימוש. חולשה שנראתה, פחד שנחשף, מבוכה, כישלון או פגיעה יכולים להיכנס אל מערכת היחסים החברתית ולהשפיע על המקום של הילד בתוכה.
אבן דומינו 9 — כל ילד היה מי ש״ראו לו״, וכל ילד היה גם מי ש״ראה לאחרים״
זו אבן שקל מאוד להעלים, והיא חיונית. בבית הילדים הילד אינו רק קורבן פוטנציאלי של המבט. הוא גם נושא מבט. כל ילד חי בשתי העמדות.
• אני רואה שאתה מפחד.
• אני רואה שהיא הרטיבה.
• אני רואה שלא באו לקחת אותך.
• אני רואה מי נעלב.
• אני רואה מי נשאר לבד.
• אני רואה איפה כואב לך.
• אני רואה מי חלש עכשיו.
כלומר, ילדים מקבלים גישה מתמשכת לחלקים הפגיעים של ילדים אחרים, לעיתים בלי שהאחר בחר לחשוף אותם בפניהם. מכאן עולה שאלה התפתחותית שלא נשאלת מספיק: מה עושה לילד עצם העובדה שהוא נדרש להיות עד מתמשך לפגיעוּת של ילדים אחרים?
אבן דומינו 10 — עמדת הרואה: להיות צופה בחולשה בתוך סביבה שמודדת חולשה
הצופה אינו ניטרלי. הוא עצמו חי בתוך אותה קבוצה, זקוק למעמד, פוחד לאבד כוח ויודע — דרך חוויותיו שלו ודרך מה שראה אצל אחרים — שחולשה יכולה להיות בעלת מחיר חברתי.
לכן כשהוא רואה ילד אחר ברגע חלש הוא אינו מקבל רק מידע רגשי. הוא מקבל גם מידע חברתי: זה מקום שבו אפשר לפגוע; זה מה שקורה למי שבוכה; כך מגיבים למי שמפחד; זה המקום שבו הילד הזה פגיע; כך אפשר להתרחק מן החלש או להצטרף אל החזק.
האם חשיפה מתמשכת לחולשותיהם של ילדים אחרים היא גם סוג של לימוד פסיבי של אכזריות ילדית?
אין כאן הנחה שילדים רעים או שאכזריות היא תכונה של בית הילדים. תחרות, קנאה, נקמה, בדיקת גבולות, לעג, משיכה אל החזק והתרחקות מן החלש הן אפשרויות טבעיות בתוך קבוצות ילדים. השאלה היא מה עושה סביבה שמעמידה בפני הילד שוב ושוב הזדמנות לראות את נקודות החולשה של האחר ולהחליט מה לעשות איתן.
אבן דומינו 11 — אולי תפקיד הסביבה המגינה הוא כפול
אנחנו רגילים לומר שסביבה מגדלת צריכה להגן על ילד מפני אכזריותם של אחרים. אבל ייתכן שיש לה תפקיד נוסף, פחות מדובר: להגן על הילד גם מפני הזמנות חוזרות להיות אכזרי בעצמו.
ילד עדיין לומד מה עושים בכוח. מה עושים כשאני יודע את נקודת החולשה של האחר? מה עושים כשהצחוק של כולם מזמין אותי להצטרף? מה עושים כשיש בידי מידע שיכול להוריד מישהו אחר במעמד? עד כמה סביבה מגדלת אמורה לצמצם מראש את הכמות והסוג של החומר הפגיע שמוחזק בידי ילדים אחרים?
פרטיות אינה מגינה רק על מי שעלול להיפגע. היא מגינה גם על האחר מפני כוח שהוא עדיין לא בשל להחזיק.
זו נקודה שתהיה חשובה מאוד בהמשך למאמר האינטימיות: לא כל מידע על אדם אחר אמור להיות ברשותי. עצם קיומו של גבול מגן על שני צדי הגבול.
אבן דומינו 12 — כשהמבט נוכח מספיק זמן, הוא עובר פנימה
כשילד חי רוב הזמן בסביבה שבה הוא יכול להיראות — ובעיקר להיראות בידי מי שמעמדו ומוגנותו תלויים בתגובותיהם — הוא מתחיל לאמץ את נקודת התצפית החיצונית כדרך זמינה מאוד להסתכל על עצמו.
• לפני ״מה אני רוצה?״ יכול להופיע ״איך זה ייראה?״
• לפני ״מה אני מרגישה?״ יכול להופיע ״מה יראו לי?״
• לפני ״מה יפה בעיניי?״ יכול להופיע ״איך זה נמדד בעיניהם?״
• לפני ״מה נכון לי?״ יכול להופיע ״מה הדבר הזה יעשה למעמד שלי?״
המבט החיצוני, כשהוא נוכח מספיק זמן, יכול להפוך לנקודת תצפית פנימית.
העיניים של האחרים אינן צריכות להישאר בחדר. אחרי זמן מספיק אנחנו יכולים לשאת אותן איתנו.
הטענה אינה שאין יותר ״אני״. היא עדינה יותר: סדר הקדימויות בין שתי נקודות התצפית עלול להשתנות. המבט מבחוץ נעשה מהיר, אוטומטי וזמין, והוא עלול להשיג — ואחר כך להסיג — את המבט מבפנים.
אבן דומינו 13 — מה משתנה כשהשאלה הראשונה משתנה?
המחיר האפשרי אינו רק מבוכה, ולא רק חסר בפרטיות. השאלה העמוקה יותר היא: מאיזו נקודת מבט למדתי לפגוש את עצמי?
אם הפרספקטיבה החיצונית מקבלת קדימות מוקדמת ואינטנסיבית, ההתבוננות בעצמי יכולה להתארגן מראש דרך השאלה כיצד אני נמדד בעיני אחרים. כאן עדיין לא נפתח את דימוי העצמי, הערך העצמי והביטחון העצמי — אלה שייכים למאמר הבא — אבל אנו מניחים את הקרקע שלהם: מי מחזיק את נקודת התצפית שממנה אני פוגש את עצמי?
כשאני לומד מוקדם מדי לראות את עצמי דרך העיניים של האחרים, המבט שלהם עלול להתחיל להקדים את המבט שלי על עצמי.
האבן האחרונה — איפה היה המקום שבו יכולתי להיות רק עם עצמי?
המאמר צריך להסתיים בשאלה, לא בתשובה. לא רק: האם היו לנו סודות? לא רק: האם הייתה פרטיות אדריכלית? אלא: איפה בחיי הילד היה מקום שבו לא היה צריך לראות את עצמו דרך שום עיניים מלבד עיניו שלו?
• לרצות בלי למדוד.
• לחשוב בלי להסביר.
• לדמיין בלי קהל.
• להשתעמם בלי שמישהו יתערב.
• להיות מוזר בלי שמישהו יראה.
• לשחק בלי שהמשחק יהפוך למידע חברתי.
• להרגיש בלי לראות איך הוא נראה כשהוא מרגיש.
• להיות עם עצמו בלי להחזיק באותו רגע את חולשותיהם של אחרים.
איפה היה המקום שבו הילד יכול היה להיות פשוט הוא — לא נצפה, לא מודד את עצמו, ולא מחזיק בידיו את חולשותיהם של אחרים?
מכאן נפתחת באופן טבעי הדרך למאמר 8 — ״אם אין אני לי, מי לי?״. השאלה הבאה כבר אינה מי רואה לי, אלא מי הוא ה״אני״ שמתוכו אני מסתכל, רוצה, מעריך, בוחר ומחזיק עמדה על עצמי.
האסימון של המאמר
״רואים לי״ אינו רק זיכרון של ילדות ללא מספיק דלתות סגורות. הוא מתאר תנאי התפתחותי שבו חלקים גדולים מן החיים מתרחשים לעיני אחרים.
הילד לומד להיות נצפה, אבל הוא גם לומד להיות צופה. הוא רואה את עצמו דרך עיני הקבוצה, ובה בעת מקבל גישה לחולשות, למבוכות ולרגעים הפרטיים של ילדים אחרים.
כאשר אין מספיק מקום מחוץ למבט, נפגע לא רק החופש להסתיר. מצטמצם גם המרחב שבו אפשר לגלות את עצמי לפני שאני מודד את עצמי דרך עיניהם של אחרים.
ובקבוצת ילדים, שבה המבט קשור גם למעמד ולמוגנות, לעיניים האלה יש כוח מיוחד. מי שרואה את החולשה שלי אינו רק עד לה; הוא גם חבר בקבוצה שבתוכה אני צריך להמשיך לחיות. ומי שאני רואה את חולשתו אינו רק ילד שאני מכיר; אני עצמי עדיין לומד מה מותר לעשות עם כוח כזה.
מה המאמר אינו טוען
• המאמר אינו טוען שכל נראות היא פגיעה. להפך — נראות היא צורך התפתחותי; הטענה היא שלצדה נחוצה גם הזכות שלא יראו לי הכול.
• המאמר אינו טוען שהפרספקטיבה החיצונית מזיקה. היא חיונית להתפתחות; השאלה היא סדר, מידה ותזמון.
• המאמר אינו טוען שילד חייב להיות פיזית לבדו שעות ארוכות. להיות לבד יכול להתקיים גם בנוכחות אדם בטוח שאינו פולש.
• המאמר אינו טוען שלילדי בית הילדים לא היה עולם פנימי, דמיון, פנטזיה או חלימה בהקיץ.
• המאמר אינו טוען שרק הילדים ראו לילדים. גם מבוגרים ראו; המבט של הילדים מקבל משמעות מיוחדת בשל הקשר למעמד ולכוח בתוך קבוצת השווים.
• המאמר אינו טוען שכל ילד השתמש בחולשות של אחרים או נעשה אכזרי. הוא שואל מהי משמעותה ההתפתחותית של חשיפה חוזרת להזדמנויות כאלה.
• המאמר אינו פותח עדיין את דימוי העצמי, הערך העצמי והביטחון העצמי. אלה נשמרים למאמר 8.
• המאמר אינו פותח עדיין את האינטימיות, הבחירה בחשיפה והאמון שהאחר לא ישתמש בקרבה כדי לפגוע. אלה נשמרים למאמר 9.
כיוונים לסיפור פתיחה מן הספר
כדאי לחפש בספר רגע פשוט מאוד בשפת הילדה שבו ה״לי״ ברור בלי פרשנות: מקלחת, בכי, גוף, פחד, הרטבה, רגע שבו לא באו לקחת, כישלון שנראה לכולם, רצון להסתיר משהו והידיעה שאין באמת אפשרות להסתיר. כמו במאמרים הקודמים, היופי יהיה בכך שהספר מתאר את הסיטואציה והמאמר נותן לה לראשונה פרשנות.
סיפור חזק במיוחד יהיה כזה שבו אין אירוע של ביוש ממש. אף אחד לא חייב לצחוק. דווקא רגע שבו הילדה רק יודעת שכולם רואים יכול להמחיש את טענת המאמר: עצם המבט משנה את תנאי החוויה.
חניון תיאורטי
היכולת להיות לבד
לבדוק לעומק את הרעיון שהיכולת להיות לבד מתפתחת תחילה דווקא בנוכחות דמות בטוחה שאינה פולשת. זהו בסיס אפשרי להבנת ההבדל בין לבדיות לבין בדידות, ובין קשר בטוח לבין נוכחות מתמדת של מבט.
ספונטניות ויוזמה
לבדוק את הקשר בין מרחב לא־נצפה לבין מחווה ספונטנית: מה יכול להתחיל מן העצמי כשאין צורך להתארגן מיד מול הסביבה. זה מתחבר לחניון הרחב של יוזמה מול תגובתיות ולמכבש ההסתגלות, אך אין לפתוח אותו במלואו כאן.
חלימה בהקיץ, פנטזיה ושעמום
לבדוק מה ידוע על תפקידם בהתפתחות העצמי, יצירתיות, ויסות, דמיון ויוזמה. לשמור על ניסוח זהיר: לא לטעון שאינם יכולים להתפתח בקבוצה, אלא לשאול מה תפקידו של מרחב לא־נצפה באיכותם ובחופש שלהם.
פרספקטיבה בגוף ראשון ובגוף שלישי
לבדוק בסיס תיאורטי מדויק להבחנה: הפרספקטיבה הפנימית שאינה נשענת קודם כול על השוואה, מול פרספקטיבה חיצונית שמכניסה מדידה, נורמות, ערכים והעדפות של אחרים. לבדוק את ההתפתחות של self-consciousness ואת הקשר בין חשיפה חברתית לבין הפנמת המבט.
המבט המתמיד והמטפורה של ״האח הגדול״
לא כמקבילה לבית הילדים ולא כהאשמה של פיקוח מכוון, אלא כחניון רעיוני: מה ידוע על כך שעצם האפשרות להיות נצפה משנה התנהגות? האם יש מושגים שימושיים על internalized observer, surveillance, self-monitoring או observer perspective שניתן לתרגם לשפה נגישה בלי להכביד על המאמר.
מעמד, כוח ומוגנות בקבוצת ילדים
לבדוק ספרות על מעמד חברתי בקבוצות ילדים, דחייה וקבלה, כוח, הגנה, פגיעות ללעג והדרה. העיקרון לשימור: מעמד אינו רק ״פופולריות״; הוא יכול להשפיע על מידת המוגנות של היחיד בתוך הקבוצה.
צפייה בפגיעוּת של האחר ולמידה של כוח
לבדוק למידה תצפיתית/שניונית לא רק בהקשר של הימנעות, אלא בהקשר של רכישת דרכי שימוש בכוח. האם חשיפה חוזרת לפגיעה, לעג או ניצול חולשה מלמדת גם את הקהל כיצד לפגוע, מתי להצטרף לצד החזק, ואילו גבולות אמורה סביבה בוגרת להציב כדי להגן על שני הצדדים.
חניון למאמרים הבאים
מאמר 8 — ״אם אין אני לי, מי לי?״
דימוי עצמי, ערך עצמי, ביטחון עצמי, ״אני״ מול ״אנחנו״, סמכות פנימית, היכולת לדעת מה נכון לי גם כאשר הסביבה רואה אותי אחרת, יוזמה והעמדה שממנה האדם מגדיר ומעריך את עצמו.
מאמר 9 — ״להתקרב או לא להתקרב? זאת השאלה״
אינטימיות, בחירה בחשיפה, גבולות, אמון, האפשרות לתת לאחר גישה לחלק פגיע בי, ״נקודות רעות״ והשימוש בקרבה או בידע אינטימי כנשק. משפט בסיס שכבר נשמר: אינטימיות מצריכה ״אני״.
נוסחים קפואים לשימור
נראות עונה לצורך שמישהו יראה אותי. פרטיות מגינה על הזכות שלא יראו לי הכול.
״רואים לי״ מתחיל במקום שבו משהו שאני חווה כשייך לי נעשה נגיש למבטו של האחר בלי שבחרתי בכך.
להיות נראה ולהיות חשוף אינם אותו הדבר.
המבט מבפנים שואל: ״מה קורה לי?״. המבט מבחוץ שואל: ״איך הדבר שקורה לי נראה ונמדד בעיני אחרים?״
היכולת לראות את עצמי מבחוץ אמורה להתווסף למבט מבפנים — לא להחליף אותו.
כשהמבט מבחוץ מתווסף במידה הנכונה, הוא משיג את המבט מבפנים ומרחיב אותו. כשהוא מגיע מוקדם מדי ובעוצמה גדולה מדי, הוא עלול להשיג אותו — ואז להסיג אותו.
פרטיות אינה רק האפשרות להסתיר מידע. היא האפשרות לחיות לרגע בלי להיות נצפה.
אחת מצורות החופש הבסיסיות ביותר היא האפשרות להפסיק להיות אובייקט למבטו של מישהו אחר.
כשאף אחד אינו מסתכל, יש הזדמנות לגלות מה מופיע בי לפני שאני בודק כיצד הוא מתקבל בחוץ.
הילד יכול להיות מוחזק בלי להיות מוחזק תחת מבט.
ההפך מ״לבד״ אינו בהכרח ״ביחד״. ההפך ממרחב פנימי הוא לפעמים ״תחת מבט״.
הילד אינו רק חי את מה שקורה לו; כמעט בו־זמנית הוא חי גם את העובדה שזה נראה.
״רואים לי״ אינו רק איום על פרטיות. בקבוצת ילדים הוא יכול להיות גם איום על המעמד — ולכן על מידת המוגנות שלי בתוך הקבוצה.
