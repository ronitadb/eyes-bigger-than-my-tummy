מסמך שלד מפורט
המסמך שומר בכוונה על פירוט רחב, על ניסוחים שנמצאו לאורך השיחה, ועל רעיונות שעדיין אינם מאמר סופי. מטרתו לשמר את העושר, ההבחנות והשרשראות התיאורטיות כדי שנוכל לעבד אותן בהמשך בלי לאבד את בחירת המילים.
1. תפקיד המאמר בתוך רצף התיאוריה
מאמר 5 עסק במראות שדרכן הילד לומד מי הוא. תגובות הסביבה אינן נשארות רק אצל האחר: חיוך, כעס, התפעלות, צחוק, התקרבות או התרחקות נעשים כולם מראות שדרכן הילד פוגש משהו מן ההשתקפות של עצמו.
מאמר 6 מתחיל בדיוק מן הנקודה הזאת, אבל עובר אל סוג מסוים מאוד של מראה: מראה שמביישת.
בושה מתעוררת כששמים לנו מראה. מראה מביישת. מראה שאומרת לנו שאנחנו לא בסדר.
מכאן המאמר עובר מן המראה אל הקבוצה: מה קורה כאשר המראה המביישת אינה רק מבט של אדם אחד, אלא אירוע שמתרחש לעיני אחרים; מה קורה כאשר הפגיעה נוגעת גם במעמד, בכוח ובשייכות; ואיך אירועים כאלה נעשים כוח מחַבְרֵת גם אצל מי שלא בוישו בעצמם אלא רק ראו מה קרה לאחרים.
המרכז של המאמר אינו "בושה" כרגש אישי בלבד. הוא בושה, ביוש, לעג והשפלה כמערכת למידה קבוצתית: כיצד היחיד לומד מה מסוכן להראות, מה עלול לעלות לו במעמד, ואיך כדאי לו לצמצם את עצמו כדי להקטין את הסיכון להיות הבא בתור.
2. ההבחנות שנרצה לשמור כבר מן ההתחלה
כדי שהמאמר לא יתערבב בין חוויה, פעולה ומנגנון קבוצתי, חשוב להחזיק כמה הבחנות בסיסיות:
בושה — החוויה הפנימית של היחיד. התחושה שאני רואה את עצמי דרך מבט שמחזיר לי משהו שקשה לי לשאת.
ביוש — פעולה, תגובה או אירוע שמייצרים או מעצימים בושה. הוא יכול להיות מכוון, אבל אינו חייב להיות מתוכנן מראש.
הלבנת פנים ברבים — ביוש שבו הקהל הוא חלק מן האירוע. הקבוצה אינה רק עדה למה שקרה; עצם העובדה שהדבר קרה לעיניה מגדילה את כוחו.
מבוכה — קרובה לבושה אך לא זהה לה; לעיתים היא רגעית יותר ופחות כוללת את העצמי כולו. בכל זאת היא חלק מאותו שדה שבו אנו נעשים מודעים לעצמנו דרך עיני האחרים.
השפלה — אינה רק כאב רגשי. בקבוצה היא יכולה לפגוע במקום, במעמד ובכוח החברתי של היחיד.
אבן דומינו 1 — בושה מתעוררת מול מראה מביישת
במאמר הקודם אמרנו שתגובות הסביבה הן מראות. הילד רואה בתוך תגובותיהם של אחרים משהו מן ההשתקפות של עצמו.
אבל לא כל מראה מחזירה לנו דבר שקל לשאת.
לפעמים המראה אומרת:
•  אתה מצחיק.
•  את משמחת.
•  אתה מעניין.
•  את רצויה.
ולפעמים היא מחזירה משהו אחר:
•  אתה מגוחך.
•  את לא בסדר.
•  אתה חלש.
•  את מביכה.
•  אתה פחות מאחרים.
•  יש בך משהו שראוי לצחוק עליו.
בושה מתעוררת כאשר מוצבת מולנו מראה מביישת — מראה שמחזירה לנו דמות של עצמנו שקשה לנו לשאת.
הבושה אינה רק "לא נעים לי שמסתכלים עליי". היא קשורה למה שאני רואה על עצמי בתוך המבט של האחר.
אם המראה מחזירה לי: "עשית משהו לא מוצלח" — זו חוויה אחת. אם היא מחזירה לי: "אתה עצמך מגוחך, דוחה, חלש, חסר ערך" — החוויה עמוקה בהרבה.
עומק הבושה הוא כגודל הכיעור שמציבה מולנו המראה.
זה אינו ניסוח שצריך להפוך בהכרח לטענה מדידה; הוא ניסוח שמחזיק את העיקרון: ככל שהמראה המביישת מאיימת יותר על תחושת הערך של האדם, כך עוצמת הבושה יכולה להיות גדולה יותר.
כאן נשמר החיבור הישיר למאמר המראות: המראה אינה רק הדרך שבה אני לומד מי אני. היא יכולה גם להפוך למקום שבו אני פוגש גרסה של עצמי שאני רוצה להסתיר, למחוק או להרחיק מן העיניים.
אבן דומינו 2 — בקבוצה, הבושה נוגעת גם במעמד ובכוח
כאשר הביוש מתרחש בתוך קבוצה, נוסף לרגש הפנימי ממד חברתי ממשי.
בקבוצה, מעמד הוא מקור כוח.
לא בהכרח כוח רשמי ולא בהכרח היררכיה שמישהו הכריז עליה. אלא המקום שלי ביחס לאחרים:
•  מי נחשב.
•  מי מוערך.
•  מי משפיע.
•  מי קובע את הטון.
•  מי מצחיק את האחרים — ומי הוא זה שצוחקים עליו.
•  מי נמצא במרכז ומי בשוליים.
•  מי יכול להרשות לעצמו לחרוג ומי משלם על חריגה מחיר גבוה.
השפלה ברבים יכולה לפגוע בדיוק במקום הזה. היא יכולה להפוך אותי לרגע, ולעיתים ליותר מרגע, ממי שיש לו כוח למי שכוחו נלקח ממנו.
הכוח של הבושה בקבוצה נובע לא רק מכך שהיא מכאיבה, אלא מכך שהיא עלולה לעלות ליחיד במעמד ובכוח חברתי.
לכן הפחד מן הבושה אינו רק פחד מתחושה לא נעימה. הוא יכול להיות פחד מן האפשרות לאבד מקום: להיות זה שכולם ראו, זה שעליו צחקו, זה שנפל במדרג, זה שהקבוצה מחזיקה עליו עכשיו ידע מביך.
והחיבור לשייכות נעשה ישיר: ככל שהמקום שלי בקבוצה חשוב לי יותר, כך האפשרות שהמראה הקבוצתית תחזיר לי דמות מושפלת נעשית מאיימת יותר.
ככל שחשוב לי יותר להיות בפנים, כך יש לקבוצה יותר כוח לקבוע כמה ממני אוכל להביא פנימה.
אבן דומינו 3 — הכוח המחַבְרֵת הגדול אינו הביוש עצמו, אלא הפחד ממנו
זו אחת מאבני המפתח החדשות של המאמר.
אם הקבוצה הייתה צריכה לבייש אותי בכל פעם מחדש כדי שאפעל לפי הנורמה, זה היה מנגנון מסורבל ולא יעיל.
אבל היא אינה צריכה.
מספיק שאלמד:
זה יכול לקרות לי.
הפחד להיות מושפל, מובך, נלעג, חשוף או זה שמאבד מעמד יכול להפוך לכוח מחַבְרֵת עצום.
הכוח המחַבְרֵת הגדול של הביוש אינו בעצם ההשפלה, אלא באפשרות שלה.
מרגע שהאפשרות הזאת הופנמה, כבר לא צריך שיהיה אירוע בכל פעם. עצם הציפייה לאירוע הבא מתחילה לארגן את ההתנהגות.
כאשר הפחד מן הביוש הופנם, הקבוצה כבר אינה צריכה לבייש אותי. אני מתחיל לשמור על עצמי בעצמי.
כאן הבושה עוברת מאירוע נקודתי למערכת בקרה. הכוח עובר מבחוץ פנימה: המבט של הקבוצה כבר אינו חייב להיות מופעל ברגע זה ממש כדי שאקח אותו בחשבון.
אבן דומינו 4 — מפגש מכלי ראשון: אני הוא זה שבויש
זה מסלול הלמידה הישיר.
עשיתי משהו. אמרתי משהו. בכיתי. נכשלתי. נחשפתי. התבלטתי. ביקשתי משהו. הקבוצה צחקה. מישהו אמר משהו בפני כולם. קיבלתי כינוי. כולם הסתכלו.
באותו רגע הילד אינו לומד רק: "זה כאב".
הוא יכול ללמוד גם:
•  כדאי שלא אגיע שוב למצב הזה.
•  מה היה בי שהפך אותי למטרה?
•  מה חשפתי שאסור היה לחשוף?
•  מה עשיתי רגע לפני שהמעמד שלי השתנה?
•  מה עליי לעשות אחרת בפעם הבאה?
האירוע נעשה חומר למידה. הילד מתחיל לבנות מפה של המצבים המסוכנים ושל הדרכים שאולי יאפשרו לו להימנע מהם.
מפגש עם ביוש → למידה → פחד → הימנעות
זהו מסלול אחד של חיברות: חוויה ישירה מלמדת את היחיד היכן עובר הגבול ומה המחיר של חריגה ממנו.
אבן דומינו 5 — מפגש מכלי שני: אני רואה מישהו אחר מושפל
אבל ילד אינו חייב להיות הקורבן כדי ללמוד את החוק.
הוא יכול לראות ילד אחר בוכה וכולם צוחקים. לראות ילדה אחרת נענשת בפני הקבוצה. לראות מישהו נופל ומקבל כינוי. לראות מישהו מודה בפחד והקבוצה משתמשת בזה נגדו. לראות הלבנת פנים ברבים — ולהבין.
אפשר ללמוד הימנעות גם בלי להיות זה שבויש.
הילד הצופה לומד:
•  ככה זה נראה כשעוברים את הגבול.
•  זה מה שעלול לקרות למי שמראה חולשה.
•  זה המחיר של חריגה.
•  את הדבר הזה עדיף לא לחשוף.
•  כאן צריך להיזהר.
למידה מכלי שני יכולה להיות יעילה במיוחד מפני שהקבוצה מצליחה "ללמד" רבים דרך אירוע שקרה לאדם אחד.
ביוש של פרט אחד יכול לחנך קבוצה שלמה.
צפייה בביוש של אחר → למידת הגבולות → פחד מן האפשרות להיות הבא בתור → הימנעות עצמית
כאן הביוש נעשה כוח מחַבְרֵת לא רק עבור האדם שחווה אותו, אלא עבור כל מי שראה והבין.
אבן דומינו 6 — הצופה לומד לא רק כיצד לא להיות הבא בתור; הוא לומד גם כיצד מפעילים את הכוח
זו אחת הנקודות העצובות והחשובות ביותר במאמר.
כאשר ילד רואה מישהו אחר מושפל, הוא לומד שתי מערכות ידע במקביל.
האחת היא מערכת ההישרדות: איך לא להיות הקורבן.
אבל השנייה היא מערכת הכוח: איך מייצרים קורבן.
הוא לומד:
•  איזה כינוי עובד.
•  איזה מקום כואב.
•  מה גורם לכולם לצחוק.
•  איך מורידים מישהו במעמד.
•  איך מצטרפים לצד החזק.
•  איך אפשר להרחיק מעצמי את הסכנה באמצעות הצטרפות למי שמבייש.
הילד הצופה אינו לומד רק כיצד לא להיות הבא בתור. הוא לומד גם מה נותן לאדם כוח על מי שעלול להיות הבא בתור.
אין כאן טענה שילדים "רעים". להפך. זו דרך להבין כיצד כוח חברתי נלמד ומתפזר בתוך קבוצה. הילד שנחשף שוב ושוב לשימוש בלעג, בהשפלה ובביוש כדרך לקבוע מעמד ונורמה, מקבל גם שיעור בשפה הזאת.
הצפייה אינה רק שיעור בהימנעות. היא יכולה להיות גם שיעור בשימוש בכוח.
צפייה בביוש של אחר → למידה כיצד כוח פועל → אפשרות להצטרף למבייש / להשתמש באותו כוח
כאן הביוש מתחיל לשעתק את עצמו בתוך הקבוצה: מי שראה יכול מחר להיות מי שמפעיל את אותה פעולה על אדם אחר.
אבן דומינו 7 — הימנעות היא אסטרטגיה שמנסה להגדיל שליטה
חשוב לא לתאר הימנעות רק כ"פחדנות" או כחולשה.
הימנעות היא אסטרטגיה.
אם איני יכול לשלוט בקבוצה, אני יכול לנסות לשלוט בחשיפה שלי אליה.
•  אני לא אגיד.
•  לא אעשה.
•  לא אראה.
•  לא אתבלט.
•  לא אבקש.
•  לא אבכה.
•  לא אודה.
•  לא אראה חולשה.
•  לא אהיה שונה מדי.
כך אני מנסה להקטין את הסיכוי שאמצא את עצמי שוב חסר שליטה בתוך רגע של השפלה.
הימנעות היא אסטרטגיה שמנסה להגדיל את השליטה שלי בסיטואציה שבה אני יודע שהקבוצה מחזיקה כוח על המעמד שלי.
היא אינה מבטלת את כוח הקבוצה. להפך: היא מלמדת כמה כוח כבר קיבל המבט הקבוצתי בתוך נפשו של היחיד.
אבן דומינו 8 — כדי לא להיות מבויש, היחיד מתחיל לצמצם את עצמו מראש
מכאן מגיע המחיר ההתפתחותי.
אם המטרה שלי היא להקטין את הסיכון להיות מושפל, אני יכול להתחיל לדכא מראש דברים מתוכי:
•  רצון.
•  העדפה.
•  גאווה.
•  חולשה.
•  סקרנות.
•  שאלה.
•  מחאה.
•  התנהגות חריגה.
•  משהו ייחודי בי שאיני בטוח כיצד יתקבל.
לא מפני שמישהו עומד מולי ואוסר עליי בכל רגע.
אלא מפני שלמדתי את המחיר האפשרי.
כדי להקטין את הסיכון לביוש, היחיד מצמצם דרגות חופש של ייחודיות, אוטונומיה, חופש ושליטה.
כאן המאמר מתחבר ישירות למאמר 4 על החוזה בין היחיד לקבוצה. ארבע דרגות החופש שהקבוצה ממילא מגבילה במידה מסוימת יכולות להצטמצם עוד יותר כאשר הפחד מהשפלה נעשה אחד הכוחות שמארגנים את ההתנהגות.
זה עדיין לא מאמר ההסתגלות. אנחנו לא מפרטות עדיין את כל הפתרונות שילדים מפתחים. אבל אנחנו כבר רואות כיצד כוח חיצוני יכול להתחיל להפוך לצמצום פנימי.
אבן דומינו 9 — הלבנת פנים ברבים: הקהל הוא חלק מן הפעולה
כאן הכותרת הראשית מתחברת ישירות לטיעון.
יש הבדל בין ביקורת לבין השפלה פומבית.
