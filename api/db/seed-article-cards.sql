איפה נמצאת אז הזירה שבה הילד יכול להשתחרר מן הכוחות הקבוצתיים ולפעול מתוך עצמו - לא בתגובה לקבוצה, אלא מתוך יוזמה?
20. חניון תיאורטי ודוגמאות לבדיקה לפני כתיבת המאמר
בשלב השלד איננו רוצים להעמיס תיאורטיקנים על הקורא, אבל כדאי לשמור מאחורי הקלעים את החיבורים שעשויים לעזור בהמשך:
