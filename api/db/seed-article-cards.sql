1. תפקיד המאמר בתוך רצף התיאוריה
מאמר 5 עסק במראות שדרכן הילד לומד מי הוא. תגובות הסביבה אינן נשארות רק אצל האחר: חיוך, כעס, התפעלות, צחוק, התקרבות או התרחקות נעשים כולם מראות שדרכן הילד פוגש משהו מן ההשתקפות של עצמו.
מאמר 6 מתחיל בדיוק מן הנקודה הזאת, אבל עובר אל סוג מסוים מאוד של מראה: מראה שמביישת.
בושה מתעוררת כששמים לנו מראה. מראה מביישת. מראה שאומרת לנו שאנחנו לא בסדר.
מכאן המאמר עובר מן המראה אל הקבוצה: מה קורה כאשר המראה המביישת אינה רק מבט של אדם אחד, אלא אירוע שמתרחש לעיני אחרים; מה קורה כאשר הפגיעה נוגעת גם במעמד, בכוח ובשייכות; ואיך אירועים כאלה נעשים כוח מחַבְרֵת גם אצל מי שלא בוישו בעצמם אלא רק ראו מה קרה לאחרים.
המרכז של המאמר אינו "בושה" כרגש אישי בלבד. הוא בושה, ביוש, לעג והשפלה כמערכת למידה קבוצתית: כיצד היחיד לומד מה מסוכן להראות, מה עלול לעלות לו במעמד, ואיך כדאי לו לצמצם את עצמו כדי להקטין את הסיכון להיות הבא בתור.
2. ההבחנות שנרצה לשמור כבר מן ההתחלה
כדי שהמאמר לא יתערבב בין חוויה, פעולה ומנגנון קבוצתי, חשוב להחזיק כמה הבחנות בסיסיות:
בושה — החוויה הפנימית של היחיד. התחושה שאני רואה את עצמי דרך מבט שמחזיר לי משהו שקשה לי לשאת.
ביוש — פעולה, תגובה או אירוע שמייצרים או מעצימים בושה. הוא יכול להיות מכוון, אבל אינו חייב להיות מתוכנן מראש.
הלבנת פנים ברבים — ביוש שבו הקהל הוא חלק מן האירוע. הקבוצה אינה רק עדה למה שקרה; עצם העובדה שהדבר קרה לעיניה מגדילה את כוחו.
מבוכה — קרובה לבושה אך לא זהה לה; לעיתים היא רגעית יותר ופחות כוללת את העצמי כולו. בכל זאת היא חלק מאותו שדה שבו אנו נעשים מודעים לעצמנו דרך עיני האחרים.
השפלה — אינה רק כאב רגשי. בקבוצה היא יכולה לפגוע במקום, במעמד ובכוח החברתי של היחיד.
אבן דומינו 1 — בושה מתעוררת מול מראה מביישת
