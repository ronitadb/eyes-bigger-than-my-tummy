בושה מתעוררת כאשר מוצבת מולנו מראה מביישת — מראה שמחזירה לנו דמות של עצמנו שקשה לנו לשאת.
הבושה אינה רק "לא נעים לי שמסתכלים עליי". היא קשורה למה שאני רואה על עצמי בתוך המבט של האחר.
אם המראה מחזירה לי: "עשית משהו לא מוצלח" — זו חוויה אחת. אם היא מחזירה לי: "אתה עצמך מגוחך, דוחה, חלש, חסר ערך" — החוויה עמוקה בהרבה.
עומק הבושה הוא כגודל הכיעור שמציבה מולנו המראה.
זה אינו ניסוח שצריך להפוך בהכרח לטענה מדידה; הוא ניסוח שמחזיק את העיקרון: ככל שהמראה המביישת מאיימת יותר על תחושת הערך של האדם, כך עוצמת הבושה יכולה להיות גדולה יותר.
כאן נשמר החיבור הישיר למאמר המראות: המראה אינה רק הדרך שבה אני לומד מי אני. היא יכולה גם להפוך למקום שבו אני פוגש גרסה של עצמי שאני רוצה להסתיר, למחוק או להרחיק מן העיניים.
