הילד הצופה אינו לומד רק כיצד לא להיות הבא בתור. הוא לומד גם מה נותן לאדם כוח על מי שעלול להיות הבא בתור.
הימנעות היא אסטרטגיה שמנסה להגדיל את השליטה שלי בסיטואציה שבה אני יודע שהקבוצה מחזיקה כוח על המעמד שלי.
כדי להקטין את הסיכון לביוש, היחיד מצמצם דרגות חופש של ייחודיות, אוטונומיה, חופש ושליטה.
ככל שחשוב לי יותר להיות בפנים, כך יש לקבוצה יותר כוח לקבוע כמה ממני אוכל להביא פנימה.
בהלבנת פנים, הקבוצה אינה רק עדה לבושה; היא נעשית אחד הכלים שמייצרים אותה.
