הכוח המחַבְרֵת הגדול של הביוש אינו בעצם ההשפלה, אלא באפשרות שלה.
מרגע שהאפשרות הזאת הופנמה, כבר לא צריך שיהיה אירוע בכל פעם. עצם הציפייה לאירוע הבא מתחילה לארגן את ההתנהגות.
כאשר הפחד מן הביוש הופנם, הקבוצה כבר אינה צריכה לבייש אותי. אני מתחיל לשמור על עצמי בעצמי.
כאן הבושה עוברת מאירוע נקודתי למערכת בקרה. הכוח עובר מבחוץ פנימה: המבט של הקבוצה כבר אינו חייב להיות מופעל ברגע זה ממש כדי שאקח אותו בחשבון.
אבן דומינו 4 — מפגש מכלי ראשון: אני הוא זה שבויש
זה מסלול הלמידה הישיר.
עשיתי משהו. אמרתי משהו. בכיתי. נכשלתי. נחשפתי. התבלטתי. ביקשתי משהו. הקבוצה צחקה. מישהו אמר משהו בפני כולם. קיבלתי כינוי. כולם הסתכלו.
באותו רגע הילד אינו לומד רק: "זה כאב".
הוא יכול ללמוד גם:
•  כדאי שלא אגיע שוב למצב הזה.
•  מה היה בי שהפך אותי למטרה?
•  מה חשפתי שאסור היה לחשוף?
•  מה עשיתי רגע לפני שהמעמד שלי השתנה?
•  מה עליי לעשות אחרת בפעם הבאה?
האירוע נעשה חומר למידה. הילד מתחיל לבנות מפה של המצבים המסוכנים ושל הדרכים שאולי יאפשרו לו להימנע מהם.
מפגש עם ביוש → למידה → פחד → הימנעות
זהו מסלול אחד של חיברות: חוויה ישירה מלמדת את היחיד היכן עובר הגבול ומה המחיר של חריגה ממנו.
אבן דומינו 5 — מפגש מכלי שני: אני רואה מישהו אחר מושפל
אבל ילד אינו חייב להיות הקורבן כדי ללמוד את החוק.
הוא יכול לראות ילד אחר בוכה וכולם צוחקים. לראות ילדה אחרת נענשת בפני הקבוצה. לראות מישהו נופל ומקבל כינוי. לראות מישהו מודה בפחד והקבוצה משתמשת בזה נגדו. לראות הלבנת פנים ברבים — ולהבין.
אפשר ללמוד הימנעות גם בלי להיות זה שבויש.
הילד הצופה לומד:
•  ככה זה נראה כשעוברים את הגבול.
•  זה מה שעלול לקרות למי שמראה חולשה.
•  זה המחיר של חריגה.
•  את הדבר הזה עדיף לא לחשוף.
•  כאן צריך להיזהר.
למידה מכלי שני יכולה להיות יעילה במיוחד מפני שהקבוצה מצליחה "ללמד" רבים דרך אירוע שקרה לאדם אחד.
ביוש של פרט אחד יכול לחנך קבוצה שלמה.
צפייה בביוש של אחר → למידת הגבולות → פחד מן האפשרות להיות הבא בתור → הימנעות עצמית
כאן הביוש נעשה כוח מחַבְרֵת לא רק עבור האדם שחווה אותו, אלא עבור כל מי שראה והבין.
אבן דומינו 6 — הצופה לומד לא רק כיצד לא להיות הבא בתור; הוא לומד גם כיצד מפעילים את הכוח
זו אחת הנקודות העצובות והחשובות ביותר במאמר.
כאשר ילד רואה מישהו אחר מושפל, הוא לומד שתי מערכות ידע במקביל.
האחת היא מערכת ההישרדות: איך לא להיות הקורבן.
אבל השנייה היא מערכת הכוח: איך מייצרים קורבן.
הוא לומד:
•  איזה כינוי עובד.
•  איזה מקום כואב.
•  מה גורם לכולם לצחוק.
•  איך מורידים מישהו במעמד.
•  איך מצטרפים לצד החזק.
•  איך אפשר להרחיק מעצמי את הסכנה באמצעות הצטרפות למי שמבייש.
הילד הצופה אינו לומד רק כיצד לא להיות הבא בתור. הוא לומד גם מה נותן לאדם כוח על מי שעלול להיות הבא בתור.
אין כאן טענה שילדים "רעים". להפך. זו דרך להבין כיצד כוח חברתי נלמד ומתפזר בתוך קבוצה. הילד שנחשף שוב ושוב לשימוש בלעג, בהשפלה ובביוש כדרך לקבוע מעמד ונורמה, מקבל גם שיעור בשפה הזאת.
הצפייה אינה רק שיעור בהימנעות. היא יכולה להיות גם שיעור בשימוש בכוח.
צפייה בביוש של אחר → למידה כיצד כוח פועל → אפשרות להצטרף למבייש / להשתמש באותו כוח
כאן הביוש מתחיל לשעתק את עצמו בתוך הקבוצה: מי שראה יכול מחר להיות מי שמפעיל את אותה פעולה על אדם אחר.
אבן דומינו 7 — הימנעות היא אסטרטגיה שמנסה להגדיל שליטה
חשוב לא לתאר הימנעות רק כ"פחדנות" או כחולשה.
הימנעות היא אסטרטגיה.
אם איני יכול לשלוט בקבוצה, אני יכול לנסות לשלוט בחשיפה שלי אליה.
•  אני לא אגיד.
•  לא אעשה.
•  לא אראה.
•  לא אתבלט.
•  לא אבקש.
•  לא אבכה.
•  לא אודה.
•  לא אראה חולשה.
•  לא אהיה שונה מדי.
כך אני מנסה להקטין את הסיכוי שאמצא את עצמי שוב חסר שליטה בתוך רגע של השפלה.
הימנעות היא אסטרטגיה שמנסה להגדיל את השליטה שלי בסיטואציה שבה אני יודע שהקבוצה מחזיקה כוח על המעמד שלי.
היא אינה מבטלת את כוח הקבוצה. להפך: היא מלמדת כמה כוח כבר קיבל המבט הקבוצתי בתוך נפשו של היחיד.
אבן דומינו 8 — כדי לא להיות מבויש, היחיד מתחיל לצמצם את עצמו מראש
מכאן מגיע המחיר ההתפתחותי.
אם המטרה שלי היא להקטין את הסיכון להיות מושפל, אני יכול להתחיל לדכא מראש דברים מתוכי:
•  רצון.
•  העדפה.
•  גאווה.
•  חולשה.
•  סקרנות.
•  שאלה.
•  מחאה.
•  התנהגות חריגה.
•  משהו ייחודי בי שאיני בטוח כיצד יתקבל.
לא מפני שמישהו עומד מולי ואוסר עליי בכל רגע.
אלא מפני שלמדתי את המחיר האפשרי.
כדי להקטין את הסיכון לביוש, היחיד מצמצם דרגות חופש של ייחודיות, אוטונומיה, חופש ושליטה.
כאן המאמר מתחבר ישירות למאמר 4 על החוזה בין היחיד לקבוצה. ארבע דרגות החופש שהקבוצה ממילא מגבילה במידה מסוימת יכולות להצטמצם עוד יותר כאשר הפחד מהשפלה נעשה אחד הכוחות שמארגנים את ההתנהגות.
זה עדיין לא מאמר ההסתגלות. אנחנו לא מפרטות עדיין את כל הפתרונות שילדים מפתחים. אבל אנחנו כבר רואות כיצד כוח חיצוני יכול להתחיל להפוך לצמצום פנימי.
אבן דומינו 9 — הלבנת פנים ברבים: הקהל הוא חלק מן הפעולה
כאן הכותרת הראשית מתחברת ישירות לטיעון.
יש הבדל בין ביקורת לבין השפלה פומבית.
יש הבדל בין: "מישהו אמר לי שעשיתי משהו לא בסדר" לבין: "כולם עכשיו יודעים שעשיתי משהו לא בסדר".
בהלבנת פנים, הקבוצה אינה רק עדה לבושה; היא נעשית אחד הכלים שמייצרים אותה.
הקהל מכפיל את הכוח מפני שהפגיעה אינה נשארת בקשר שביני לבין מי שמבקר אותי. היא משנה את האופן שבו אני חושש שהקבוצה כולה רואה אותי.
וכאשר זו הקבוצה שאיתה אני צריך להמשיך לחיות, לשחק, לאכול, לישון ולהשתייך — הפגיעה אינה מסתיימת כשהאירוע מסתיים.
היא יכולה להישאר במרחב החברתי: מי שמע, מי זוכר, מי יכול להשתמש בזה שוב, מה קרה למעמדי, והאם המראה המביישת הפכה מעכשיו לחלק מן הדרך שבה הקבוצה רואה אותי.
אבן דומינו עשר — בית הילדים: שוב שאלת האינטנסיביות
רק כאן נכנס בית הילדים במלואו.
לא בטענה ששם הומצאו בושה, לעג, השוואה או ביוש. הם קיימים בכל קבוצת ילדים ובכל חברה אנושית.
השאלה שלנו, שוב, היא של מידה, משך ודומיננטיות.
אם אותם ילדים הם מי שרואים אותי:
•  בארוחה.
•  במקלחת.
•  בבכי.
•  בכישלון.
•  בפחד.
•  במריבה.
•  בהרטבה.
•  בהצלחה.
•  במבוכה.
•  בהשכבה.
•  ובבוקר שאחרי.
ואם הם גם אותם אנשים שאיתם אני צריך להמשיך לחיות מחר, מחרתיים ובשנים הבאות — אז מחיר הביוש מקבל עוצמה אחרת.
אין כמעט "אחרי" שבו אפשר פשוט להיעלם מן האירוע.
אין הרבה זירות שבהן המעמד שלי אחר, שבהן הסיפור מאבד מכוחו, או שבהן אני יכול להיות אדם שאינו קשור למה שקרה בקבוצה.
לא מנגנון אחר — אינטנסיביות אחרת.
וככל שהזירה הקבוצתית אינטנסיבית יותר, כך גם הפחד מן הביוש יכול להפוך לכוח מחַבְרֵת חזק יותר.
אבן דומינו אחת עשרה — האסימון
המאמר צריך להוביל את הקורא להבנה שהכוח המחַבְרֵת של בושה אינו נמצא רק באירוע המביש עצמו.
בושה היא כוח מחַבְרֵת לא רק מפני שהשפלה כואבת. כוחה הגדול נמצא בלמידה שנוצרת סביבה.
הילד יכול ללמוד מכלי ראשון — כאשר הוא עצמו מבויש — או מכלי שני, כאשר הוא רואה מה קורה לאחרים שחורגים.
מן המפגש נולד פחד; מן הפחד נולדת הימנעות; וההימנעות מלמדת את הילד לצמצם מראש רצונות, התנהגויות וחלקים מעצמו שעלולים לסכן את מעמדו בקבוצה.
והלמידה מכלי שני מחזיקה גם אפשרות נוספת:
כאשר ילד לומד שוב ושוב את חוקי הביוש, הוא אינו לומד רק כיצד לא להיות מושפל. הוא עלול ללמוד גם כיצד להשפיל.
כך הביוש יכול לפעול בכמה מעגלים בבת אחת: על הקורבן, על הצופים, על הנורמה הקבוצתית ועל חלוקת הכוח בתוך הקבוצה.
3. שלוש שרשראות העבודה של המאמר
כדי לשמור את המהלך ברור, כדאי להחזיק שלוש שרשראות נפרדות. הן אינן חייבות להופיע כך במאמר הסופי, אבל הן מבהירות לנו את המנגנון.
שרשרת היחיד
מראה מביישת → בושה → מפגש עם ביוש → למידה → פחד → הימנעות → צמצום עצמי
זהו המסלול שבו אירוע ישיר נעשה חומר לחיזוי ולהתנהגות עתידית.
שרשרת הצופה
צפייה בביוש של אחר → למידת הגבולות → פחד מן האפשרות להיות הבא בתור → הימנעות עצמית
זהו המסלול שבו קבוצה שלמה יכולה ללמוד את גבולותיה דרך מה שקרה לפרט אחד.
שרשרת העברת הכוח
צפייה בביוש של אחר → למידה כיצד כוח חברתי פועל → אפשרות להצטרף לצד החזק / להשתמש באותו כוח
זהו המסלול שבו הביוש אינו רק מחנך את הקורבן והצופים, אלא גם מלמד את שפת הכוח עצמה.
4. נקודות שחשוב לשמור ולא לפתח עדיין יתר על המידה
מעמד הוא מושג חשוב מאוד למאמר הזה, אבל לא צריך להפוך את המאמר כולו למאמר על היררכיה קבוצתית. מספיק להניח שבקבוצה למיקום החברתי יש ערך וכוח, ושביוש יכול לפגוע בהם.
מבוכה צריכה להופיע כחלק מן השדה, אבל לא להכריע כאן אם היא רגש נפרד מבושה או דרגה אחרת שלה. זה יכול להישאר לחניון התיאורטי.
חשיפה ו"רואים לנו" קשורים מאוד לכוח הבושה, אבל הם ראויים למאמר אחר. כאן אפשר להזכיר שככל שיש פחות אפשרות להסתיר, כך המבט הקבוצתי זמין יותר — בלי לפתוח עדיין את כל נושא הגוף, הסודות והפרטיות.
אנחנו עדיין לא נכנסות לעומק למנגנוני הגנה והסתגלות. ההימנעות מופיעה כאן מפני שהיא חלק ישיר משרשרת הלמידה של הביוש, אבל לא נפתח עדיין את כל סוגי ההסתגלויות שנוצרו.
5. מה המאמר אינו טוען
כדי לשמור על התזה המבנית ולא להפוך את המאמר להאשמה, חשוב להחזיק גבולות ברורים:
•  המאמר אינו טוען שבושה היא רגש מיותר או פתולוגי. היא רגש חברתי נורמלי וחלק מתהליכי חיברות.
•  המאמר אינו טוען שכל לעג או צחוק הם טראומה.
•  המאמר אינו טוען שילדים שמביישים אחרים הם "רעים". הוא מבקש להבין כיצד כוח נלמד ומופץ בתוך קבוצה.
•  המאמר אינו טוען שכל ביוש בבית הילדים היה מכוון או יזום בידי מבוגרים.
•  המאמר אינו טוען שהביוש הוא כוח החיברות היחיד. הוא אחד מן הכוחות שפועלים לצד נורמות, השוואה, קונפורמיות, תגמולים וסנקציות אחרות.
•  המאמר אינו טוען שכל ילד הגיב לביוש בהימנעות. הימנעות היא אחת האסטרטגיות האפשריות; הסתגלויות אחרות יפותחו במאמרים מאוחרים יותר.
•  המאמר אינו טוען שהבעיה היא עצם קיום הבושה בקבוצה. כמו לאורך כל התזה, השאלה היא מידה, אינטנסיביות, משך והיעדר זירות מאזנות.
6. סיפור הפתיחה — מה לחפש בספר
כמו במאמרים הקודמים, הספר יכול להיות מקור מצוין לסצנה קטנה שהילדה המספרת אינה מפרשת.
הסיפור הטוב ביותר יהיה רגע שבו המראה המביישת נוצרת בפשטות: מישהו אומר דבר, אחרים צוחקים; ילד נחשף; אירוע פרטי נעשה ציבורי; כינוי נדבק; מבוגר פונה אל הקבוצה; או ילדה רואה מה קורה למישהו אחר ומבינה משהו על מה לא כדאי לעשות.
אפשר לחפש שתי צורות של סיפור:
סיפור מכלי ראשון — הילדה עצמה היא זו שעליה מסתכלים, צוחקים, מעירים או מצביעים.
