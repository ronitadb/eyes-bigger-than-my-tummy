אבן דומינו 4 — המראה אינה רק מילים
זה חשוב מאוד.
מרבית המירורינג אינו שיעור שהמבוגר מעביר לילד.
אמא אינה צריכה לומר: "אני חושבת שאתה מצחיק". הצחוק שלה עושה את העבודה.
מבוגר אינו צריך לומר: "את מכבידה עליי עכשיו". הפנים, אנחת הרווחה כשהילדה מתרחקת, חוסר הסבלנות — יכולים לשקף זאת.
ומנגד: עיניים שנפתחות, חיוך, התקרבות, סקרנות, התפעלות, יכולת להישאר — גם אלה מראות.
המראה עוברת דרך:
•  פנים.
•  טון.
•  צחוק.
•  שתיקה.
•  התקרבות.
•  התרחקות.
•  מבוכה.
•  כעס.
•  התפעלות.
•  חוסר סבלנות.
•  עניין.
•  שעמום.
•  רצון בקרבה.
•  הימנעות.
כלומר, עוד לפני שהילד יודע לנסח את השאלה:
מה קורה לאחרים כשאני מופיע?
הוא כבר מקבל עליה אלפי תשובות קטנות. והתשובות האלה מתחילות להצטבר.
אבן דומינו 5 — לילד יש כמה מראות
חשוב מאוד שלא לבנות תמונה מלאכותית שבה רק האם או ההורה משקפים את הילד.
יש מראות רבות: הורים, אחים, סבים, מטפלים, גננות, ילדים אחרים.
כל אחת מהן יכולה לראות חלקים אחרים ולהחזיר תגובות אחרות.
וזה כשלעצמו חלק חשוב מהחיים.
אותו ילד יכול להיות מצחיק עם אדם אחד, שקט עם אדם אחר, נועז במקום אחד, ביישן במקום אחר.
העולם אינו מחזיר לו תמונה אחת אחידה.
אבל בראשית החיים, המראה של המבוגרים המטפלים והמעגל הקרוב היא בדרך הטבע מראה בעלת משקל מיוחד.
לא משום שהם תמיד צודקים.
לא משום שהם תמיד רואים היטב.
אלא משום שהם בדרך כלל המראה הקרובה, הרציפה והדומיננטית ביותר בשנות ההתפתחות הראשונות.
אבן דומינו 6 — מראה בוגרת יכולה לעבד לפני שהיא מחזירה
זו אבן מפתח של המאמר.
ההבדל בין מראה של מבוגר מטפל לבין מראת קבוצת השווים אינו שהמבוגר "טוב" והילדים "רעים".
גם מבוגרים יכולים לראות ילד באופן חלקי, שגוי, מוטה, פוגעני או מצמצם.
גם בבית הילדים לא נכון להניח שהמראה שהמטפלות נתנו הייתה בהכרח המראה "הנכונה".
ההבדל הוא בפונקציה שהמבוגר מסוגל עקרונית למלא.
למבוגר המטפל יש יכולת פוטנציאלית לעשות דבר שילד בן אותו גיל עדיין אינו מסוגל לעשות באותה מידה:
לעצור בין מה שראה לבין האופן שבו הוא מגיב.
הוא יכול לראות את הילד כועס ולא להגיב מיד בכעס משלו.
הוא יכול לשאת את העלבון לפני שהוא משיב.
הוא יכול להבין שהתנהגות אינה כל הילד.
הוא יכול להחזיק היסטוריה: היום היא מתפרצת, אבל אני מכיר אותה גם מאתמול ומלפני חודש.
הוא יכול להחזיק סתירה: הילד שפגע הוא גם ילד שנפגע. הילדה העצמאית מאוד היא גם הילדה שזקוקה עכשיו לעזרה.
הוא יכול לשים את הרגע בתוך הקשר.
הוא יכול להפריד בין: מה הילד עשה — לבין — מי הילד.
הוא יכול לראות מופע קשה — ולא להחזיר לילד את המופע כולו כזהות.
מראה בוגרת אינה רק מגיבה לילד. היא יכולה לעבד את מה שהיא רואה לפני שהיא מחזירה אותו אליו.
זה אחד ממשפטי המפתח של המאמר.
אפשר להעמיק אותו מעט: המבוגר אינו רק לוח מבריק שמחזיר בדיוק את מה שפגע בו. יש לו אפשרות להיות מראה מעבדת.
הוא מקבל משהו מן הילד, מחזיק אותו לרגע בתוך נפש בוגרת יותר, ומחזיר אותו באופן שאפשר לילד לפגוש.
לא תמיד. לא כל מבוגר. לא בכל רגע. אבל זו פונקציה התפתחותית שמבוגר יכול למלא.
אבן דומינו 7 — קבוצת השווים היא מראה מסוג אחר
גם ילדים אחרים הם מראות. וזו אינה תקלה בהתפתחות. להפך.
יש דברים שילד יכול ללמוד על עצמו דווקא מתוך המפגש עם שווים:
•  האם כיף לשחק איתי.
•  איך אחרים מגיבים לי כשאין מבוגר שמתווך.
•  האם אני יודע להצטרף.
•  האם אני משתלט.
•  האם אני נדיב.
•  האם אנשים רוצים להיות קרובים אליי.
•  האם הבדיחה שלי מצחיקה גם ילדים אחרים.
•  האם אני טוב במשחק.
•  מה קורה לי בתחרות.
•  מה אני עושה כאשר אני מפסיד.
מראת השווים נותנת לילד מידע אמיתי וחשוב על האופן שבו הוא מתקיים בין שווים.
לכן אין כאן ניסיון להעמיד את המראה של המבוגר כ"אמת" ואת המראה של הילדים כ"שיבוש".
שתיהן נחוצות. שתיהן חלק מההתפתחות. אלא שהן מראות מסוגים שונים.
והילדים שמחזיקים את המראה הקבוצתית אינם עומדים מחוץ למערכת.
גם הם ילדים. גם הם עסוקים בבניית עצמם. גם הם מחפשים שייכות. גם הם פוחדים מדחייה. גם הם מתחרים, מקנאים, נעלבים, רוצים מעמד, רוצים להרגיש טוב ביחס לאחרים.
המראה של קבוצת השווים אינה עומדת מחוץ למערכת. היא עצמה כפופה לכוחות של הקבוצה.
וזה המקום שבו מאמר 5 מתחבר ישירות למאמר 4.
אבן דומינו 8 — מראת הקבוצה מושתתת על השוואה
זה החידוד המרכזי החדש.
קבוצת שווים היא מעצם טבעה מרחב של השוואה.
•  מי מהיר יותר.
•  מי חזק יותר.
•  מי יפה יותר.
•  מי אמיץ יותר.
•  מי מקובל יותר.
•  מי מצחיק.
•  מי יודע.
•  מי מצליח.
•  מי מקבל יותר.
•  מי בוכה.
•  מי מפחד.
•  מי נבחר.
•  מי נשאר בחוץ.
אין כאן טענה שהשוואה היא דבר רע.
מושג ההשוואה מוטמע באדם.
אנחנו מבינים את עצמנו גם ביחס לאחרים. אנחנו לומדים דרך השוואה. קבוצת שווים מטבעה נותנת לילד סרגלים רבים שבאמצעותם הוא יכול למקם את עצמו בעולם.
וההשוואה הזאת נחוצה.
אבל שוב חוזרת שאלת המידה.
יש הבדל בין מפגש עם מראת ההשוואה במשך חלקים מסוימים מן היום, לבין חיים בתוכה כמעט ברציפות.
עשרים שעות של השוואה אינן פשוט "עוד השוואה".
זו כבר אינטנסיביות אחרת.
וכל זה מתרחש בזמן שהנפש עדיין רכה ומתעצבת.
הילד עדיין בונה את תמונתו על עצמו. הגבולות בין "מי אני" לבין "מה מחזירים לי שאני" עדיין בתהליך בנייה.
ולכן הנפש הצעירה היא מטבעה נוחה מאוד להשפעה, גמישה, susceptible למה שמוחזר אליה שוב ושוב.
לא כפתולוגיה. זו בדיוק תכונתה ההתפתחותית.
ילד צריך להיות גמיש מספיק כדי ללמוד מן הסביבה. אבל אותה גמישות פירושה גם שהוא רגיש מאוד ללחץ חוזר ועקבי.
חיים תחת מראה אינטנסיבית מדי, שמושתתת במידה רבה על השוואה, הם חיים תחת לחץ מתמשך על העצמי המתהווה.
ופה מופיע לראשונה, אולי רק כזרע, המושג:
מכבש ההסתגלות
לא לפתח עדיין את כל ההסתגלויות. לא לומר עדיין מה הילד עשה. רק לזהות את הלחץ.
הקבוצה משווה. הילד רואה את עצמו בתוכה. והנפש המתעצבת נדרשת שוב ושוב לפגוש את הפער בין עצמה לבין מה שמוחזר אליה.
מראת ההשוואה, כשהיא אינטנסיבית מספיק, יכולה להפוך ממקור מידע למכבש.
הרחבה בתוך אבן 8 — אין צורך שהקבוצה "תחליט" להשוות
השוואה קבוצתית אינה פעולה רשמית.
אף אחד אינו צריך לומר: "הבה נשווה עכשיו בין הילדים".
עצם החיים זה לצד זה מייצרים אותה.
•  מי ראשון.
•  מי אחרון.
•  מי בכה.
•  מי הצליח.
•  מי קיבל.
•  מי נבחר.
•  מי לא.
•  מי יפה.
•  מי גדול.
•  מי קטן.
•  מי "כמו כולם".
ולכן ההשוואה אינה בהכרח תוצאה של תרבות רעה או חינוך שגוי.
היא כוח טבעי של קבוצת שווים.
וזה בדיוק מחזיר אותנו לעקרון הגדול של כל התיאוריה: הבעיה אינה בהכרח בקיומו של הכוח. השאלה היא מה המידה?
כמה שעות ביום? באילו זירות? כמה אפשר לצאת ממנו? מה מאזן אותו?
הערת דיוק — היו גם מראות של מבוגרים
אין צורך להפוך את זה לאבן בפני עצמה.
לאורך המאמר צריך לשמור רק על הדיוק: מראת הקבוצה לא החליפה באופן מוחלט את מראת המבוגרים.
היו מטפלות. היו הורים. היו מבוגרים משמעותיים. וגם הם החזירו לילד מראות.
אין כאן טענה שהילד בבית הילדים ראה את עצמו רק דרך הקבוצה.
וגם אין טענה שמראת המבוגרים הייתה בהכרח מראה מדויקת, מיטיבה או מעבדת.
השאלה שלנו אינה מי "צדק". השאלה היא איזו מראה נעשתה דומיננטית יותר מתוך תנאי החיים עצמם.
אבן דומינו 9 — המראה הדומיננטית היא המראה שנעשית חלק מרכזי מן האופן שבו אני רואה את עצמי
זו האבן האחרונה.
בדרך הטבע, בראשית החיים, הילד חי בעיקר בתוך המעגל הקרוב שלו.
ההורה והמבוגרים המטפלים הם בדרך כלל המראות הנוכחות ביותר.
ולכן הילד מפנים בראש ובראשונה את המראות שהם מציבים לו.
לא מפני שמראת ההורים "נכונה".
אלא מפני שהיא דומיננטית.
זו המראה שהוא פוגש שוב ושוב. זו המראה שמלווה את רוב רגעי החיים. זו המראה הזמינה לו כשהעצמי עדיין מתהווה.
בחינוך המשותף השתנתה חלוקת המשקל בין המראות.
הילד חי את רוב שעות ימיו בנוכחות קבוצת השווים.
הקבוצה ראתה. הגיבה. השוותה. צחקה. התקרבה. התרחקה. התפעלה. לעגה. בחרה. לא בחרה.
ובמשך שעות רבות מאוד ביום הילד קיבל ממנה מידע על עצמו.
ולכן הטיעון שאנחנו מבקשות להניח הוא פשוט:
בדרך הטבע הילד מפנים בראש ובראשונה את המראה שמציב לו המעגל המטפל הקרוב, משום שזו המראה הדומיננטית מבין המראות הזמינות לו. בחינוך המשותף, מראת קבוצת השווים קיבלה משקל דומיננטי במיוחד משום שהילד חי בתוכה במשך רוב שעות חייו.
לא: המראה הייתה רעה.
לא: המטפלות לא ראו.
לא: הקבוצה אמרה לילד דברים שקריים.
רק:
מי שמחזיק את המראה רוב הזמן מקבל משקל גדול במיוחד באופן שבו הילד לומד לראות את עצמו.
והטענה שלנו היא שבחינוך המשותף קבוצת הילדים הייתה מראה דומיננטית באופן שאינו מאפיין את מבנה החיים ההתפתחותי הרגיל.
כאן המאמר צריך לעצור.
לא לעבור עדיין לזהות. לא לומר עדיין מה נשאר בבגרות. לא לתאר עדיין הסתגלויות. זה מספיק.
האסימון של המאמר
ילד אינו לומד מי הוא רק מתוך עצמו. הוא פוגש את עצמו גם בתוך התגובות שהוא מעורר באחרים. חיוך, כעס, התפעלות, צחוק, התקרבות או התרחקות נעשים כולם מראות שדרכן הילד לומד משהו על עצמו.
במבנה ההתפתחותי הרגיל, מראת המבוגרים המטפלים מקבלת בראשית החיים משקל גדול במיוחד. לא משום שהיא תמיד נכונה, אלא משום שהיא המראה הדומיננטית: הקרובה, החוזרת והנוכחת ביותר.
גם קבוצת השווים היא מראה חשובה ונחוצה. אבל זו מראה מסוג אחר. היא מוחזקת בידי ילדים אחרים, והיא מושתתת במידה רבה על השוואה.
בחינוך המשותף השתנה היחס בין המראות. כאשר קבוצת השווים נוכחת במשך רוב שעות היום, כמעט בכל זירות החיים, מראת ההשוואה מקבלת משקל חריג דווקא בשנים שבהן תפיסת העצמי עדיין מתהווה.
השאלה אינה אם המראה הקבוצתית הייתה טובה או רעה.
השאלה היא מה קורה לנפש צעירה וגמישה כאשר היא נדרשת לראות את עצמה שעות רבות כל כך בתוך מראה שמבוססת על השוואה.
ומכאן אפשר להניח, בלי לפתח עדיין:
מכבש ההסתגלות.
מה המאמר אינו טוען
•  המאמר אינו טוען שהורים רואים את ילדיהם תמיד באופן נכון.
•  הוא אינו טוען שהמטפלות בבית הילדים לא שיקפו לילדים דבר.
•  הוא אינו טוען שמראת המבוגר טובה ומראת הילד רעה.
•  הוא אינו טוען שהשוואה חברתית היא דבר פתולוגי.
•  הוא אינו טוען שילד צריך לגדול בלי קבוצת שווים.
•  הוא אינו טוען שכל תגובה של הקבוצה נהפכת לזהות.
•  הוא אינו טוען עדיין שהקבוצה קיבעה תפקידים, גרמה לבושה, יצרה קונפורמיות מסוימת או הולידה מנגנוני הגנה.
