השפלה ברבים יכולה לפגוע בדיוק במקום הזה. היא יכולה להפוך אותי לרגע, ולעיתים ליותר מרגע, ממי שיש לו כוח למי שכוחו נלקח ממנו.
הכוח של הבושה בקבוצה נובע לא רק מכך שהיא מכאיבה, אלא מכך שהיא עלולה לעלות ליחיד במעמד ובכוח חברתי.
לכן הפחד מן הבושה אינו רק פחד מתחושה לא נעימה. הוא יכול להיות פחד מן האפשרות לאבד מקום: להיות זה שכולם ראו, זה שעליו צחקו, זה שנפל במדרג, זה שהקבוצה מחזיקה עליו עכשיו ידע מביך.
והחיבור לשייכות נעשה ישיר: ככל שהמקום שלי בקבוצה חשוב לי יותר, כך האפשרות שהמראה הקבוצתית תחזיר לי דמות מושפלת נעשית מאיימת יותר.
ככל שחשוב לי יותר להיות בפנים, כך יש לקבוצה יותר כוח לקבוע כמה ממני אוכל להביא פנימה.
