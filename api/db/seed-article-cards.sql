• כוחות קבוצתיים כלליים - נורמות, חיברות, קונפורמיות, סנקציות, תגמולים, גבולות לשונות ומנגנונים שמחזיקים השתייכות. אין צורך בשלב זה לייחס כל כוח לתיאוריה מסוימת בטקסט הפומבי.
• הבחנה בין כניסה לקבוצה, אפשרות יציאה, עוצמת דרישות הקבוצה, משך החשיפה וזירות מאזנות. ההשערה שלנו כרגע היא שהמשתנה המכריע לבית הילדים הוא בעיקר האינטנסיביות והדומיננטיות לאורך זמן, ולא רק חוסר הבחירה.
• הדוגמה של "עולים" ו"יורדים" - דוגמה זמינה לכוח סמוי של שפה שמצמיד ערכיות להשתייכות ולעזיבה.
• הדוגמה שהועלתה בדיון על מסורת בעדה הדרוזית של בחירה בוגרת בהמשך ההשתייכות - לשמור כחומר אפשרי בלבד ולבדוק עובדתית באופן מדויק לפני כל שימוש בפרסום.
• הניסוח המספרי "כ-20 שעות ביממה, 7 ימים בשבוע, מלידה עד הגיוס" - מייצג כרגע את רעיון האינטנסיביות. לפני פרסום יש לוודא את הנתונים וההבדלים ההיסטוריים בין לינה משותפת, תקופות וקיבוצים שונים.
