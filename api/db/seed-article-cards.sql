מאמר 4 - מסמך שלד מפורט / "הספרייה המשותפת" - עיניים גדולות זה לא טוב
סטטוס: מסמך עבודה מפורט. מטרתו לשמר את מהלך החשיבה, בחירות המילים, הניסוחים שנמצאו וההבחנות שהתגבשו בשיחה לפני כתיבת המאמר הספרותי עצמו. זהו עדיין שלד: הוא מחזיק את הטיעון, את אבני הדומינו, את הדוגמאות ואת המקומות שדורשים בדיקה או פיתוח.
1. תפקידו של המאמר בשרשרת
שלושת המאמרים הראשונים עסקו בעיקר בסביבה המגדלת ובפונקציות שהילד זקוק להן בתוכה: מותאמות לצרכים, רציפות והיסטוריה, ולאחר מכן נראות. מאמר 4 פותח ציר חדש בסדרה: לא עוד רק מה צריך הילד מן המבוגר או מן הסביבה המטפלת, אלא מה קורה כאשר הילד חי כחלק מקבוצה, ומהם הכוחות שנוצרים מעצם קיומה של קבוצה.
המאמר אינו אמור להיות "מבוא לפסיכולוגיה של קבוצות" במובן הבוגר והארגוני. אנחנו מדברות על קבוצה מראשית חיי האדם, עוד לפני שילד מבין היסטוריה, מטרה, שם, אידאולוגיה או זהות קולקטיבית. לכן אנחנו מחפשות שפה גולמית ובסיסית יותר: האדם הוא יצור חברתי; הוא זקוק לאחרים; התאגדות בקבוצה מספקת מוגנות; ובתמורה הקבוצה זקוקה לכך שהיחיד יהיה פרט בתוכה.
החוזה הוא מושג מרכזי במאמר: בין היחיד לקבוצה יש יחסים של קבלה ונתינה. הקבוצה נותנת ומקבלת מן היחיד; היחיד נותן לקבוצה ומקבל ממנה.
מאמר 4 צריך להניח את התשתית שעליה יישענו בהמשך מאמרים על מירורינג קבוצתי, נורמות, חריגה, קונפורמיות, בושה, מעמד, "מה אחרים חושבים", זהות וכוחות נוספים. כאן עדיין לא נפתח כל כוח בנפרד. המטרה היא שהקורא יבין מדוע לקבוצה יש כוח מלכתחילה, מה היא מעניקה ליחיד, מה היא דורשת כדי להמשיך להתקיים, ואילו משתנים קובעים אם הכוח הזה מאוזן.
2. הכניסה ממאמר 3: נראות היא גם הדלת דרכה אני רואה את עצמי
המעבר מן המאמר על נראות צריך להיות מדויק. הטיעון איננו: "מישהו רואה אותי ואז מחזיר לי מראה". הרי מאמר 3 עצמו מציב סימן שאלה על דרגת הנראות בבית הילדים. אם נדרוש נראות עמוקה כתנאי למראה, נסתור את הטיעון שלנו.
נראות אינה רק כשהאחר רואה אותי. נראות היא גם הדלת דרכה אני רואה את עצמי.
בהתפתחות נורמטיבית קיימות זו לצד זו נראות תפקודית ונראות-של-מֵעֵבֶר. אין אחת "נכונה" יותר והשנייה נכונה פחות. שתיהן נחוצות ושתיהן מתרחשות באופן טבעי. הילד זקוק לכך שהסביבה תקלוט את המופעים שלו - מה הוא עושה, איך הוא מתנהג, מה קורה בפועל - וגם לכך שמישהו יוכל, בחלק מן הרגעים, לראות מעבר למופע אל הילד שבתוכו.
שני אופני הנראות מגיעים אל הילד לא רק כמידע שהמבוגרים מחזיקים עליו, אלא דרך האופן שבו הסביבה קולטת אותו ומגיבה אליו. התגובות של האחרים הן חומר שממנו הילד מתחיל לבנות ידע על עצמו.
• אמא צוחקת ממני - משהו בי לומד: אני מצחיק.
• אמא שמחה ממני - משהו בי לומד: אני משמח.
• אמא כועסת עליי - משהו בי לומד: אני יכול להכעיס.
• אני בוכה ומישהו נבהל מאוד; אני גאה ומישהו מתפעל; אני גאה ומישהו אחר מקטין - בכל אחד מן המקרים אני פוגש משהו מעצמי בתוך תגובתו של האחר.
התגובות של הסביבה אליי הן מראות. אני רואה באחרים שמגיבים אליי את ההשתקפות של "מי אני".
ובבית הילדים היו לילד שתי מערכות גדולות של מראות:
מראת המבוגרים ומראת הקבוצה.
מכאן אנחנו פונות לראשונה אל הקבוצה. לא כדי לפתח עדיין את המירורינג, אלא כדי להבין את הזירה שמחזיקה את אחת המראות המרכזיות בחיי הילד: מהי קבוצה, מה היחיד מקבל ממנה, מה היא חייבת לקבל ממנו, ואילו כוחות נוצרים כדי שהיחסים האלה יישמרו.
3. אבן דומינו ראשונה - "לא טוב היות האדם לבדו": מוגנות והחוזה הראשוני
המאמר מתחיל מן הדבר הבסיסי ביותר, לפני תרבות, אידאולוגיה או ערכים. האדם הוא יצור חברתי. בני אדם מתאגדים בקבוצות משום שלקבוצה יש כוח שאין ליחיד לבדו. יותר אנשים יכולים להגן, לשמור, להתריע על סכנה, לסייע, לחלוק משאבים ולעמוד לצד היחיד כשהוא חלש.
לכן המתנה הראשונית והגולמית של הקבוצה היא מוגנות. לפני גאוות יחידה, טקסים, משמעות או ערכים משותפים, קיימת חוויה בסיסית יותר: אני לא לבד מול העולם.
הקבוצה תיתן ליחיד הגנה שהוא לא יכול לספק לעצמו לבד. מה היחיד ייתן לקבוצה בתמורה? את הדבר שהיא חייבת ואינה יכולה להתקיים בלעדיו - את הפרטים שמרכיבים אותה.
קבוצה איננה יכולה להתקיים בלי אנשים שרואים את עצמם כפרטים בתוכה. לכן כבר כאן נמצא גרעין החוזה: היחיד מתחייב להיות חלק מן הקבוצה; הקבוצה מתחייבת, במידה מסוימת, להגן על היחיד ולקיים את האינטרסים שלו כחלק מן האינטרסים שלה.
המחויבות של היחיד להיות פרט בתוך הקבוצה היא החמצן של הקבוצה.
היחיד נותן לקבוצה השתייכות ומחויבות. הקבוצה נותנת ליחיד מוגנות.
4. אבן דומינו שנייה - דמיון ושונות
מרגע שקיימת קבוצה, נוצרת שאלה בסיסית: כמה דומה היחיד צריך להיות לאחרים כדי להישאר פרט לגיטימי בתוכה, וכמה שונה הוא יכול להיות בלי לסכן את השייכות.
כאן אנחנו משאירות את ה"אנחנו" כמושג משני ולא מעמיסות עליו. העיקר פשוט יותר: קבוצה יוצרת דמיון ומאפשרת דרגות חופש שונות של שונות. אין צורך שכל הפרטים יהיו זהים; להפך, קבוצה יכולה להכיל שונות רחבה. אבל אין קבוצה שאין לה שום גבול לשונות שהיא יכולה לשאת.
קבוצה יוצרת דמיון ומאפשרת דרגות חופש שונות של שונות.
לכל קבוצה יש דרגות חופש משלה לשונות.
המשמעות היא שקבוצות שונות יכולות לעמוד במקומות שונים מאוד על הרצף: יש קבוצות שמאפשרות שונות רבה, ויש קבוצות שבהן טווח השונות המצופה מן הפרטים צר. אין כאן עדיין שיפוט מוסרי. זהו מאפיין של החוזה הקבוצתי.
5. אבן דומינו שלישית - עקרון החוזה: הקבוצה והיחיד נותנים ומקבלים
כאן המאמר מבסס במפורש את הקונספט של החוזה. בין היחיד לקבוצה מתקיימים יחסי חליפין: הקבוצה מקבלת מן היחיד דברים שהיא זקוקה להם כדי להתקיים, והיחיד מקבל מן הקבוצה דברים שאין לו אפשרות לקבל באותה צורה לבדו.
הקבוצה מקבלת מן היחיד בראש ובראשונה את המחויבות שלו להיות פרט בתוכה. בלי פרטים אין קבוצה. היחיד מקבל מן הקבוצה מוגנות, והקבוצה משיבה לו בהתחייבות הדדית: לקיים ולהגן על האינטרסים שלו כל עוד הם יכולים להתקיים בתוך האינטרסים והקיום של הקבוצה.
מכאן נובע גבול מובנה: הקבוצה אינה יכולה להבטיח להגן על אינטרסים של יחיד אם אותם אינטרסים פוגעים באינטרסים החיוניים שלה, מאיימים על קיומה, או גורמים לפרטים להפסיק לראות את עצמם כחלק ממנה. קבוצה שאינה מצליחה לשמור על השתתפותם של פרטים חדלה בסופו של דבר להיות קבוצה.
לכן היחיד, מעצם ההשתייכות, מקבל על עצמו במידה כלשהי ערכים, אינטרסים, התנהגויות ואמונות שלא יסכנו את הקיום המשותף. ההסכמה הזו כרוכה בוויתור. לא בוויתור מוחלט, ולא בהכרח באותו ויתור בכל קבוצה, אלא בצמצום של דרגות חופש בארבע חזיתות מרכזיות:
• ייחודיות - כמה אני יכול להיות שונה מן האחרים ועדיין להישאר בפנים.
• שליטה - כמה אני קובע את מה שקורה וכמה אני נדרש לקבל החלטות של אחרים או של הקבוצה.
• חופש - כמה אני רשאי לפעול לפי רצוני בלבד וכמה אני מחויב לאחרים ולקבוצה.
• אוטונומיה - כמה אני מגדיר בעצמי ערכים, כללים, משמעות ודרך פעולה, וכמה מהם מגיעים אליי מתוך הסביבה הקבוצתית.
אין צורך לסדר את המתנות והוויתורים בצמדים סימטריים. השייכות עצמה כרוכה בוויתורים בכל ארבע החזיתות; גם התרבות, הביטחון, החברויות, הנאמנות וההשתתפות במשהו גדול מן היחיד כרוכים בהן באופן חופף. יש "הכול בהכול".
עצם ההשתייכות מכניסה אותי למערכת שבה הייחודיות, השליטה, החופש והאוטונומיה שלי מוגבלים במידה כלשהי.
מכאן עולה מושג שיהיה חשוב לכל חטיבת הקבוצה: לכל קבוצה יש תנאי חוזה אחרים, ולכן לכל קבוצה יש דרגות חופש אחרות בארבע האיכויות האלה.
6. אבן דומינו רביעית - הכוחות הקבוצתיים: איך הקבוצה "גובה" את החוזה
לחברה ולקבוצה יש דרכים רבות להבטיח את השתתפות הפרטים, מפני שבלי השתתפותם אין קבוצה. אין צורך שמישהו יתכנן את כל הדרכים האלה. חלקן מתפתחות מעצם החיים המשותפים.
בשלב הזה המאמר צריך להזכיר את הכוחות רק באופן כללי, כדי לתת לקורא שפה שתשמש אותנו בהמשך:
• נורמות - מה נחשב "ככה עושים פה", גם כאשר הדבר אינו כתוב.
• חיברות - התהליך שבו היחיד לומד מה צריך להיות ולעשות כדי להיחשב פרט לגיטימי בתוך הקבוצה.
• תגמולים - הערכה, מעמד, קרבה, הכרה או שייכות הניתנים למי שמייצג היטב את הדרך והעקרונות של הקבוצה.
• סנקציות - המחיר שמוצמד לחריגה: ביקורת, לעג, התרחקות, הדרה, אובדן מעמד, שיפוט מוסרי או ענישה רשמית.
• קונפורמיות - התנועה הטבעית של היחיד לכיוון המשותף כאשר חשוב לו להמשיך להשתייך.
ככל שחשוב לי יותר להיות בפנים, כך יש לקבוצה יותר כוח לקבוע כמה ממני אוכל להביא פנימה.
הנקודה המבנית היא שקבוצה אינה זקוקה ל"אדם רע" כדי להפעיל כוח על היחיד. הכוחות נוצרים מפני שהקבוצה צריכה לשמור על תנאי הקיום שלה ועל המשך השתתפות חבריה.
7. אבן דומינו חמישית - כוח גלוי, כוח סמוי והערך המוסרי של השתייכות
חלק מן הכוח הקבוצתי גלוי: יש חוק, איסור, תפקיד, החלטה, שכר או עונש. אבל חלק גדול מן הכוח פועל בצורה סמויה. אף אחד אינו חייב לומר במפורש מה מותר ומה אסור; הפרטים לומדים את הגבולות דרך תגובות הסביבה.
• מבט, צחוק או שתיקה.
• מי מקבל הערכה ומי נעשה מושא ללעג.
• מי זוכה בקרבה ומי נדחק לשוליים.
• איזה אדם מוצג כדוגמה טובה ואיזה אדם כמישהו שלא רוצים להיות כמוהו.
• איזו שפה משמשת לתיאור הישארות, חריגה או עזיבה.
הדוגמה של "עולים" ו"יורדים" חזקה משום שהיא מראה איך שפה יכולה להצמיד דירוג ערכי לבחירה בלי החלטה רשמית. מי שבוחר לבוא ולהתגורר בישראל "עולה"; מי שבוחר לעזוב אותה מכונה לעיתים "יורד". בתוך המילים עצמן נטענת היררכיה של עלייה וירידה. זו דרך פשוטה, סמויה ועוצמתית להעביר מסר על ערך ההשתייכות ועל ערך העזיבה.
אפשר לצמצם את האפשרות לעזוב קבוצה בלי לאסור על אף אחד לעזוב אותה. די להפוך את העזיבה לדבר שמספר משהו שלילי על האדם שעוזב.
קבוצה יכולה לאכוף כלל בלי שאיש יאמר אותו.
אחד מסימני הכוח של נורמה הוא שהאלטרנטיבה כלל אינה עולה כשאלה.
חיברות "מצליח" מאוד כאשר הכלל כבר אינו נחווה ככלל שצריך לאכוף. הוא פשוט נעשה הדרך שבה העולם מובן: ככה עושים, ככה נכון, ככה ראוי. בשלב הזה הכוח כמעט אינו זקוק להפעלה חיצונית.
8. אבן דומינו שישית - הכוחות האלה נורמטיביים: השאלה היא דרגות החופש
חשוב מאוד שהמאמר לא יהפוך את נורמות הקבוצה, הסנקציות, החיברות או הקונפורמיות לסימן לפתולוגיה. בלי מנגנונים שמחזיקים את הקבוצה, היא אינה יכולה לתת ליחיד את מה שהוא מבקש ממנה. אם אין נאמנות, אין ביטחון בנאמנותם של האחרים. אם אין שום נורמה, קשה לקיים פעולה משותפת. אם אין שום גבול לשונות, הקבוצה עלולה לאבד את מה שמחבר בין פרטיה.
הכוחות שמגבילים את היחיד הם גם הכוחות שמאפשרים לקבוצה להתקיים ולהעניק לו את מה שהוא מקבל ממנה.
לכן השאלה אינה אם הקבוצה "גובה מחיר". כל השתייכות גובה מחיר מסוים. השאלה היא מה תנאי החוזה וכמה דרגות חופש הוא משאיר ליחיד.
לא עצם קיומו של החוזה קובע את מידת החופש של היחיד, אלא תנאי החוזה.
חברות וקבוצות אנושיות מתקיימות על רצף רחב מאוד. יש מבנים חברתיים שמאפשרים מעט דרגות חופש ויש כאלה שמאפשרים רבות. לאורך ההיסטוריה אפשר למצוא כמעט כל מיקום על הרצף. אין צורך במאמר הזה להכריע מי "נכון". הרעיון הוא להבין שיש טווח, ושארבע האיכויות - ייחודיות, שליטה, חופש ואוטונומיה - יכולות להצטמצם או להתרחב במידות שונות.
9. אבן דומינו שביעית - בחירה ויכולת יציאה הן חלק מן המשוואה, אבל אינן כל התזה
אותו ויתור מקבל משמעות אחרת כאשר אדם בוחר להשתייך לקבוצה וכאשר הוא יכול, לפחות עקרונית, להפסיק להשתייך אליה. לכן חשוב להכניס למודל שני משתנים: עד כמה היחיד בוחר להיכנס לחוזה, ועד כמה הוא יכול לצאת ממנו.
אצל מבוגרים, מידה של בחירה מאפשרת לנהל את העסקה: לבחור קבוצה אחרת, להפחית מעורבות, לשנות את תנאי ההשתייכות או לעזוב כאשר המחיר אינו מתאים עוד. אבל חשוב שלא להפוך את הבחירה לעיקרון היחיד שמסביר את הבעיה של בית הילדים. ילדים ממילא אינם בוחרים חלק גדול מן הקבוצות והמסגרות בחייהם, ולעיתים היעדר הבחירה עצמו הוא מה שמגן עליהם.
היעדר בחירה הוא משתנה חשוב - אבל הבעייתיות של בית הילדים אינה מוסברת רק בכך שהילד לא בחר בקבוצה.
10. אבן דומינו שמינית - המבוגרים בקיבוץ והעסקה הלגיטימית
העמדה של המאמר אינה מבטלת את עקרונות הקיבוץ ואת החינוך הקיבוצי. להיפך: היא מאפשרת להבחין בין עקרונות לבין שאלת האיזון והמידתיות.
חברי קיבוץ מבוגרים בחרו להשתייך לקבוצה. הם קיבלו דברים שרצו בהם - שייכות, ביטחון, שותפות, תרבות, ערכים, מטרות, מפעל משותף - והסכימו לוותר על דרגות מסוימות של חופש, שליטה, אוטונומיה וייחודיות. אפשר להסכים או לא להסכים עם תנאי העסקה, אבל זו הייתה עסקה לגיטימית בין מבוגרים בוחרים.
זו הייתה עסקה לגיטימית בין מבוגרים שבחרו בה.
הנקודה הזו חשובה כדי שהמאמר לא יישמע כהאשמה של עצם הרעיון הקבוצתי. התזה אינה אומרת שה"אנחנו" פסול. היא שואלת מה קורה כאשר אותו חוזה חברתי מועבר אל ילדים, ואיזה איזון ניתן להם בין הזירות שבהן הקבוצה קודמת לבין הזירות שבהן היחיד יכול להתרחב.
11. אבן דומינו תשיעית - ילדים אינם בוחרים את רוב תנאי ילדותם
ילדים אינם מבוגרים בוחרים. הם אינם בוחרים את משפחתם, אינם מחליטים אם ללכת לגן או לבית הספר, ואינם בוחרים את כל תנאי חייהם. זה טבעי, ולעיתים חיוני להגנתם. לכן אסור להפוך את עצם העובדה שהילד לא בחר בקבוצת השווים שלו להוכחה שמשהו השתבש.
ובכל זאת, הבחירה המוגבלת של ילדים היא חלק מן ההקשר שבו צריך להסתכל על החינוך המשותף. ההורים, כחברי הקיבוץ, קבעו שהילד ישתייך לקבוצה מעצם היותו ילדם ומעצם השתייכותם שלהם לקיבוץ. עבור הילד הקבוצה לא הייתה אופציה מתוך כמה אפשרויות, אלא עובדת חיים.
זו הייתה קבוצה שאי אפשר היה לבחור שלא להשתייך אליה.
זו הייתה קבוצה שכמעט אי אפשר היה להחליף.
הקבוצה נקבעה כמעט מרגע הלידה, והילד נשאר בה לאורך שנות הילדות והנעורים. מכאן עולה רעיון "החוזה שעבר בירושה": המבוגרים בחרו בחוזה שלהם; הילד נולד לתוך תנאיו.
עסקה נבחרת אצל המבוגר נעשתה מציאות נתונה אצל הילד.
החינוך המשותף העביר לילדים לא רק את המתנות של החברה הקיבוצית, אלא גם את חוזה ההשתייכות שלה - עוד לפני שהייתה להם היכולת לבחור אם הם רוצים לחתום עליו.
12. אבן דומינו עשירית - כשהאלטרנטיבה אינה עולה כשאלה
בבית הילדים לא היה צורך בהכרח לומר לילד במפורש: "אסור לך לעזוב את הקבוצה". כאשר כל מבנה החיים אומר שוב ושוב "זו הקבוצה שלך", האפשרות לא להשתייך יכולה כלל לא להופיע כאפשרות שאפשר לחשוב עליה.
זהו כוחו של חיברות עמוק: הכלל אינו נחווה כאחת האפשרויות אלא כמציאות. הילד אינו בהכרח שואל "האם אני רוצה להיות חבר בקבוצה הזאת?" משום שאין סביבו סימנים שהשאלה עצמה קיימת.
אחד מסימני הכוח של נורמה הוא שהאלטרנטיבה כלל אינה עולה כשאלה.
הנקודה הזו חשובה למאמרי ההמשך: כוחות קבוצתיים חזקים במיוחד אינם תמיד אלה שצועקים הכי חזק. לעיתים הם אלה שכבר אין צורך לומר בקול.
13. אבן דומינו אחת-עשרה - הבעיה המרכזית: אינטנסיביות, דומיננטיות והיעדר זירות מאזנות
כאן נמצא החידוד המרכזי שאליו הגיע הדיון. הבעיה אינה עצם קיומם של הכוחות הקבוצתיים. היא אינה מוסברת רק בכך שהילד לא בחר בקבוצה. והקבוצה אינה "רעה" משום שיש בה נורמות, חיברות, לחץ לדמיון, סנקציות, נאמנות וקונפורמיות. כל אלה קיימים בקבוצות והם חלק מן החוזה הקבוצתי.
הכוחות של קבוצת הילדים בבית הילדים לא היו חריגים משום שקבוצת הילדים הייתה "רעה". נורמות, חיברות, לחץ לדמיון, סנקציות ונאמנות קיימים בכל קבוצה - והם חלק ממה שמאפשר לקבוצה לספק לחבריה מוגנות ושייכות.
הבעייתיות מתחילה בשאלת המידה: כמה אינטנסיבית הייתה הזירה הקבוצתית, כמה פונקציות חיים התרחשו בתוכה, כמה זמן היא הייתה פעילה, וכמה מרחבים היו לילד שבהם הכוחות שלה אינם נקודת הייחוס.
במצב אנושי נורמטיבי, אדם נע בין זירות שבהן דרגות החופש מצומצמות לבין זירות שבהן הן גדלות. בעבודה הוא מקבל כללים, תפקיד, מחויבויות ומגבלות; אחר כך הוא חוזר לביתו ויכול לבחור יותר, לשלוט יותר, להיות ייחודי יותר, להתנהג באופן שאינו מוכתב על ידי הקבוצה המקצועית. אדם יכול להיות חבר בצוות אחד, בן משפחה במקום אחר, חבר בקבוצה אחרת, ולפעמים פשוט לבדו.
המחיר שהיחיד משלם לקבוצה נעשה בר-נשיאה משום שהוא אינו נדרש בדרך כלל לשלם אותו בכל זירות חייו.
כך נוצרת מערכת של איזונים. במקום אחד ה"קבוצה" מקבלת קדימות; במקום אחר היחיד יכול להרחיב מחדש ייחודיות, שליטה, חופש ואוטונומיה. האיזון אינו דורש בהכרח "קבוצה טובה יותר". הוא דורש גם מקומות שבהם האדם אינו נדרש להיות חבר קבוצה בכלל.
האיזון לכוחה של קבוצה אינו בהכרח קבוצה טובה יותר. הוא גם קיומם של מקומות שבהם האדם אינו צריך להיות חבר קבוצה כלל.
איפה אני לא צריך בכלל לחשוב על השאלה אם אני דומה או שונה?
זהו חידוד חשוב: גם קבוצה ליברלית מאוד עדיין מחזיקה את תודעת הקבוצה. אני עדיין קורא תגובות, יודע שיש אחרים, יודע שיש נורמות. המרחב המאזן הוא לעיתים מרחב שבו הקבוצה חדלה להיות נקודת הייחוס שלי.
14. אבן דומינו שתים-עשרה - יוזמה מול תגובתיות
מתוך שאלת הזירות המאזנות עולה הבחנה נוספת שאנחנו רוצות לשמור: חיים בקבוצה דורשים בהכרח מידה של תגובתיות. אני צריך להביא בחשבון את האחרים - מה הם רוצים, מה מקובל, האם עכשיו תורי, איך הדבר שלי משפיע על הקבוצה, מה המקום שלי ביחס לאחרים. זה נורמלי וחיוני לחיים משותפים.
אבל ההתפתחות זקוקה גם למרחבים שבהם הילד יכול לפעול מתוך יוזמה שאינה תגובה לכוחות הסביבה: לרצות משהו מפני שהוא רוצה אותו; לשחק מפני שזה מעניין אותו; לבחור; להמציא; להיות לבד; להעדיף; לנוע מתוך ספונטניות לפני שהוא בודק כיצד הדבר יתקבל.
כדי שהיחיד יוכל לחיות בתוך קבוצה בלי להיעלם בתוכה, הוא זקוק גם למרחבים שבהם אינו נדרש להיות כל הזמן בתגובה לקבוצה.
זהו המקום שבו, בחניון התיאורטי, עולה הקו הוויניקוטיאני של ספונטניות מול compliance ושל "אני אמיתי" מול "אני כוזב". עדיין לא נכניס את המונחים למאמר עצמו ולא נסיק מהם מסקנה קלינית גורפת. כרגע הם עוזרים לנו לחשוב על השאלה: כמה מקום היה למחווה שמקורה בילד עצמו, וכמה מן החיים דרשו הסתגלות רצופה לשדה הקבוצתי.
15. אבן דומינו שלוש-עשרה - בית הילדים כשדה החיים הדומיננטי
עכשיו אפשר להניח את שאלת בית הילדים במלוא עוצמתה. קבוצת השווים לא הייתה עוד קבוצה אחת בחיי הילד. היא הייתה סביבת חיים מרכזית שבה התרחשו אכילה, משחק, למידה, רחצה, מריבות, שינה, בוקר, ערב וחלק גדול מאוד מן החיים היומיומיים, לאורך שנים.
בדיון שלנו השתמשנו בניסוח "כ-20 שעות ביממה, שבעה ימים בשבוע, מלידה ועד הגיוס" כדי לתפוס את האינטנסיביות. לפני פרסום נצטרך לדייק היסטורית את המספרים ואת ההבדלים בין תקופות וקיבוצים; בשלד העבודה חשוב לשמור את העיקרון: זירת החיים שבה דרגות החופש הקבוצתיות מצומצמות יחסית הייתה דומיננטית מאוד בזמן, במרחב ובמספר פונקציות החיים שהיא החזיקה.
לא האם היו בבית הילדים כוחות קבוצתיים - בוודאי שהיו. השאלה היא איזה משקל קיבלו הכוחות האלה בנפש כאשר כמעט כל החיים התרחשו בשדה הפעולה שלהם.
וכאן נשאלת שאלת האיזון: איפה הייתה הזירה שבה הילד יכול היה להשתחרר מכוחות הקבוצה? איפה יכול היה לא להיות "אחד מהקבוצה"? איפה יכול היה לבטא ייחודיות, שליטה, חופש ואוטונומיה בלי שהביטוי הזה יעבור דרך השאלה איך הוא מתקבל בתוך הקבוצה?
איפה, בחינוך המשותף, היה המקום שבו הילד יכול היה להיות פשוט הוא - לא אחד מהקבוצה, לא בתגובה לקבוצה, לא תחת המבט שלה, אלא מתוך יוזמה, ספונטניות ובחירה?
16. האסימון המרכזי של המאמר
האסימון אינו שקבוצת הילדים הייתה רעה, וגם לא שכל כוח קבוצתי הוא בעייתי. להפך: המאמר מבקש לתת לכוחות הקבוצתיים לגיטימציה מלאה כחלק מן החוויה האנושית. קבוצה צריכה לייצר דמיון, נורמות, חיברות, נאמנות ומידה של קונפורמיות כדי שתוכל להתקיים ולהעניק מוגנות ושייכות.
האסימון הוא שאלת האיזון בין זירות. בני אדם אינם אמורים בהכרח לחיות כל הזמן באותו יחס בין "אני" לבין קבוצה. הם נעים בין סביבות שמבקשות יותר מחויבות, ויתור והתאמה לבין סביבות שבהן הייחודיות, השליטה, החופש והאוטונומיה יכולים להתרחב.
השאלה היא של מידה.
מה קורה כאשר הזירה שבה דרגות החופש מצומצמות נעשית סביבת החיים הדומיננטית - במשך רוב שעות היממה, בכל ימות השבוע, מראשית החיים ולאורך שנים?
איפה נמצאת אז הזירה שבה הילד יכול להשתחרר מן הכוחות הקבוצתיים ולפעול מתוך עצמו - לא בתגובה לקבוצה, אלא מתוך יוזמה?
זהו האסימון שמאפשר לתזה להישאר נאמנה לעצמה: היא אינה מבטלת את עקרונות הקיבוץ והחינוך הקיבוצי. היא מדברת על איזונים, על מידתיות ועל היחס בין זירות החיים.
17. ההרמה להנחתה למאמרים הבאים
המאמר אינו צריך לפרט עדיין מה עשתה הקבוצה לילדים. הוא מניח את החוקיות שבתוכה יוכלו המאמרים הבאים לבחון כוחות מסוימים: מירורינג, נורמות, חריגה, בושה, מעמד, קונפורמיות, זהות והמבט של אחרים.
החיבור בחזרה למראה צריך להישאר עדין: התחלנו בכך שהתגובות של הסביבה הן מראות שדרכן הילד רואה משהו מעצמו. בבית הילדים אחת המראות הגדולות הייתה קבוצת השווים. אחרי שהבנו את החוזה הקבוצתי ואת דרגות החופש שהוא מייצר, נוכל במאמר הבא לשאול לא רק מה הילדים האחרים חשבו עליי, אלא מהי האיכות של מראה שמוחזקת בתוך שדה קבוצתי חזק ורציף.
מה מחזירה לילד מראה שמוחזקת בידי קבוצה שהוא חייב להמשיך להשתייך אליה?
אולם אין הכרח להחליט כבר עכשיו שהמאמר הבא יהיה מירורינג. מאמר 4 צריך לעמוד בפני עצמו כמאמר היסוד לציר הקבוצה. משם נוכל לבחור את אבן הדומינו הטבעית ביותר לפי הסיפור והחומר שיגיעו.
18. מה המאמר אינו טוען
• הוא אינו טוען שקבוצה היא דבר רע. להפך: קבוצה מספקת מוגנות ושייכות והיא חלק בסיסי מן החיים האנושיים.
• הוא אינו טוען שנורמות, חיברות, קונפורמיות או סנקציות הן כשלעצמן פתולוגיות.
• הוא אינו טוען שהעובדה שילד אינו בוחר את הקבוצה שלו היא כשלעצמה פגיעה. ילדים אינם בוחרים חלק גדול מתנאי חייהם.
• הוא אינו מבטל את הבחירה הלגיטימית של מבוגרים לחיות בקיבוץ ולקבל על עצמם חוזה קבוצתי עם דרגות חופש מצומצמות יותר בתחומים מסוימים.
• הוא אינו טוען שכל קיבוץ, תקופה או קבוצת ילדים פעלו באותה צורה. התזה היא מבנית ועוסקת בעקרון של משקל, אינטנסיביות ואיזון.
• הוא עדיין אינו קובע אילו מנגנוני הגנה או הסתגלויות נוצרו אצל הילדים. זה שייך לשלב מאוחר יותר בסדרה.
• הוא אינו מחייב בשלב הזה לחבר בכוח את הקבוצה למותאמות או לנראות. אם החיבורים האלה יתבררו מתוך החומר, נוסיף אותם; לא נבנה אותם מראש כדי להשלים סימטריה.
