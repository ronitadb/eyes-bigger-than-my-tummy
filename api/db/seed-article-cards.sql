בושה מתעוררת כאשר מוצבת מולנו מראה מביישת — מראה שמחזירה לנו דמות של עצמנו שקשה לנו לשאת.
עומק הבושה הוא כגודל הכיעור שמציבה מולנו המראה.
הכוח של הבושה בקבוצה נובע לא רק מכך שהיא מכאיבה, אלא מכך שהיא עלולה לעלות ליחיד במעמד ובכוח חברתי.
הכוח המחַבְרֵת הגדול של הביוש אינו בעצם ההשפלה, אלא באפשרות שלה.
כאשר הפחד מן הביוש הופנם, הקבוצה כבר אינה צריכה לבייש אותי. אני מתחיל לשמור על עצמי בעצמי.
