מאמר 10 — מסמך שלד מפורט
מסמך עבודה לשימור המבנה, אבני הדומינו, המושגים, ההבחנות, הניסוחים המדויקים והחניון התיאורטי. לא גרסת מאמר סופית לפרסום.
תפקיד המאמר בתוך רצף התיאוריה
המאמר הזה פותח את ענף המוגנות. אחרי שעסקנו במותאמות, כתובת ורציפות, נראות, כוחות הקבוצה, מראות, ביוש, פרטיות, עצמי ואינטימיות, מגיעה שאלה בסיסית אחרת: מי שומר על הילד בתוך עולם של ילדים?
הלב אינו טענה שילדים הם רעים. להפך: ילדים יכולים להיות אוהבים, נדיבים, אמפתיים, מגוננים ומסורים מאוד זה לזה. אבל הם עדיין ילדים, והכלים שמרסנים כוח, נקמה, קנאה, לעג, תחרות ואכזריות עדיין מתפתחים. לכן ילד זקוק למבוגר לא רק שיאהב אותו או יטפל בו, אלא גם שישמש כוח מגן בתוך עולם חברתי שילדים לבדם אינם יכולים להיות בו גם הקבוצה וגם המנגנון הבוגר שמרסן את כוחותיה.
הלב של המאמר: ילד אינו אמור להיות זה שצריך להיות חזק מספיק, מותאם מספיק או חכם מספיק כדי להבטיח שלא יפגעו בו. הוא זקוק למישהו חזק ממנו שיעמוד לצדו.
אבן דומינו 1 — ״ילדים יכולים להיות אכזריים״. אבל למה?
זה משפט שגור. כמעט כולם מכירים אותו. אבל כדאי לעצור ולשאול מה הוא בעצם אומר.
הוא לא אומר שילדים רעים. ילדים יכולים להיות אוהבים, נדיבים, אמפתיים, מגוננים ומסורים מאוד זה לזה. ובאותו זמן הם עדיין ילדים.
היכולת לעצור דחף, להחזיק בו־זמנית את הכעס שלי ואת הכאב של האחר, להבין עד הסוף את השלכות הפעולה שלי, לוותר על ניצחון, לרסן נקמה, לא להשתמש בכוח שיש לי — כל אלה הן יכולות שמתפתחות.
ילד יכול לדעת שחברו בוכה ובכל זאת לצחוק; לכעוס ולהשתמש בנקודה הרעה שהוא מכיר; להצטרף לצד החזק כדי לא להיות הבא בתור; לנקום בלי לשאת במלואו את ההשלכות; לגלות כמה כוח יש לו על ילד אחר ולנסות אותו. לא מפני שהוא ״ילד רע״, אלא מפני שהמערכות שמרסנות את הכוח הזה עדיין אינן בוגרות.
ילדים אינם זקוקים להגנה מפני ילדים משום שילדים הם רעים. הם זקוקים להגנה משום שילדים עדיין לומדים מה עושים בכוח, בכעס, בקנאה, בתחרות ובחולשה של האחר.
וזה בדיוק אחד מתפקידי המבוגר: לא רק לנחם אחרי שמישהו נפגע, אלא ליצור עולם שבו הכוחות הטבעיים של קבוצת ילדים אינם נשארים ללא בלמים של מבוגר.
״בעל זבוב״ יכול לשמש כאן כמטפורה בלבד, לא כהשוואה עובדתית לבית הילדים. הוא מחדד את השאלה: מה קורה כאשר משאירים קבוצת ילדים להיות גם החברה וגם מערכת הוויסות של החברה?
אי אפשר לצפות מקבוצת ילדים להיות גם הקבוצה וגם המנגנון הבוגר שאמור לרסן את כוחותיה.
אבן דומינו 2 — מוגנות פירושה שמישהו חזק ממני מחזיק עבורי את הגבול
הילד אינו אמור לדעת תמיד מתי זה כבר לא משחק, מתי הילד השני עבר גבול, איך לעצור קבוצה, איך לצאת מחרם, איך להתמודד עם ילד חזק ממנו, איך למנוע השפלה או איך לגרום לאחרים להפסיק.
לכן מוגנות אינה רק העובדה שבאותו יום לא פגעו בי. היא גם ידיעה שיש מערכת חזקה ממני שיכולה להתערב כששלי אינו מספיק.
• מישהו שרואה.
• מישהו שיודע.
• מישהו שיש לו סמכות.
• מישהו שיש לו יותר כוח ממני ומהילד שפוגע בי.
• ומישהו שמוכן להשתמש בכוח הזה לטובתי.
מוגנות פירושה שלא אני צריך להיות חזק מספיק כדי למנוע מן החזק ממני לפגוע בי. מישהו חזק ממני צריך לעמוד לצדי.
זו אינה הבטחה שלא אכאב, שלא אריב, שלא אעלב או שלא אצטרך ללמוד להתמודד. זו הידיעה שכאשר הדבר חורג מיכולת ההתמודדות שלי, איני נשאר לבדי מולו.
אבן דומינו 3 — כאן נכנסת תלות
ילד הוא יצור תלוי. לא ככישלון, לא כחולשה אישיותית, אלא כמצב התפתחותי.
הוא תלוי במבוגר למזון, קורת גג וטיפול — אבל גם לדברים פחות מוחשיים: להבין מה קורה, להבחין בסכנה, לפרש מצב, לעצור אדם אחר, לקבוע גבול ולהגן עליו כשהוא אינו מסוגל להגן על עצמו.
התלות של הילד היא לא הבעיה. היא הסיבה שהסביבה צריכה להיות אמינה.
אם אני תלויה בך, אני זקוקה לכך שהכוח שלך יהיה זמין לי כששלי אינו מספיק. תלות מיטיבה מלמדת: מותר לי להיות קטנה מול משהו גדול ממני, משום שיש מי שמחזיק עבורי את מה שאינני יכולה להחזיק לבד.
כאן כבר מסתתר משהו חשוב מאוד לחיים הבוגרים: מה קורה כשהחוויה המוקדמת מלמדת שתלות אינה מבטיחה הגנה? מה קורה כשהמצב שבו אני זקוקה למישהו אחר הוא דווקא המצב שבו אני הכי חשופה לכך שלא יהיה מי שיעזור?
אז תלות עצמה עלולה להיעשות מצב שקשה מאוד לשאת. לא מפני שהאדם ״לא יודע להישען״, אלא מפני שהוא למד מוקדם שתלות אינה בהכרח מקום בטוח.
אבן דומינו 4 — בית הילדים כעולם חברתי בפני עצמו
קבוצת הילדים בבית הילדים אינה רק קבוצה שנפגשת כמה שעות ביום. היא עולם שלם. היא המקום שבו אוכלים, משחקים, רבים, מתקלחים, נרדמים, מתעוררים, נבחרים, נדחים, מתקרבים ומתרחקים.
ובתוך העולם הזה נוצרים באופן טבעי: מעמד, כוח, קואליציות, חברויות, יריבויות, תחרות, קנאה, לעג, נקמה, משחקי כוח, ילדים חזקים יותר ופחות, ילדים שמבינים מהר יותר איך להתנהל בקבוצה וכאלה שפחות.
כבר אמרנו בענפים הקודמים: מעמד הוא במידה מסוימת כוח, וכוח הוא במידה מסוימת מוגנות. מי שנחשב, שמקשיבים לו, שבוחרים בו ושיש לו בריתות חברתיות הוא לעיתים מוגן יותר ממי שקל לבטל, ללעוג לו או להעלים אותו.
השאלה של המאמר: מי מגן על הילד מפני הכוחות הטבעיים של הקבוצה עצמה?
אבן דומינו 5 — המבוגרים אינם יכולים להגן ממה שהם אינם רואים
פה יש נקודה מבנית, לא האשמה של מטפלת מסוימת. גם מטפלת טובה אינה יכולה לדעת כל מה שמתרחש בין ילדים רבים שחיים יחד לאורך שעות רבות.
חלק מן הכוח החברתי מופעל כשאף מבוגר אינו מסתכל: במילה קטנה, בכינוי, במי לא בוחרים, במבט, במי שמפסיקים לדבר איתו, במה שקורה במיטה הסמוכה, במה שכולם יודעים אבל אף אחד לא אומר למבוגר.
ילדים גם לומדים מהר מה אפשר לעשות בלי שהמבוגרים ידעו. יש עולם רשמי של הקבוצה, ויש עולם של יחסי כוח שמתנהל מתחת לפני השטח.
לכן השאלה אינה אם הייתה מטפלת טובה. השאלה המבנית היא:
האם המבנה אפשר למבוגר לדעת מספיק על העולם החברתי שבתוכו הילד נדרש לחיות?
והרי אותו עולם הוא גם המקום שממנו הילד אינו יכול באמת לצאת. הוא אינו יכול להחליט שהיום הוא לא מגיע לקבוצה, להחליף קבוצה, לחזור לבית אחר שמחזיק עבורו זהות ומעמד אחרים. הקבוצה היא סביבת החיים.
אבן דומינו 6 — ומה קורה כשהמבוגרים עצמם משתמשים בכוחות הקבוצה לחיברות?
כאן מאמר 6 חוזר. אם מערכת המבוגרים עצמה משתמשת לעיתים בביוש, חשיפה בפני כולם, לעג, לחץ קבוצתי, ״שכולם ידעו״ או העמדה מול הקבוצה, הילד לומד דבר מורכב מאוד.
לא רק שהקבוצה יכולה לפגוע בי. גם המבוגר עשוי להשתמש בקבוצה עצמה כדי לשנות אותי.
הדבר מחליש את ההפרדה שהיינו רוצים בין הכוח שמאיים עליי לבין הכוח שאמור להגן עליי. המבוגר אינו רק מי שעוצר את המבט, הלעג והלחץ החברתי; לעיתים הוא מגייס אותם ככלי חינוכי.
כדי שהמבוגר יוכל להיות מקור למוגנות מפני כוח הקבוצה, הוא צריך לעמוד במידה מסוימת מחוץ לכוח הזה — ולא להשתמש בו שוב ושוב ככלי חינוכי.
אבן דומינו 7 — ומה אם הדרך להיות מוגן היא להשתנות?
כאן חוזרים למאמר 1, אבל בשפה פשוטה וקונקרטית.
אם אני נלעג כי אני בוכה — כדאי שאפסיק לבכות.
אם אני נפגע כי אני חריג — כדאי שאהיה פחות חריג.
אם אני מטרה כי אני חלש — כדאי שלא יראו חולשה.
אם אני נדחה בגלל משהו בי — כדאי שאשנה את הדבר הזה בי.
הילד יכול ללמוד שההגנה אינה מגיעה רק מבחוץ. הוא צריך לייצר אותה באמצעות שינוי של עצמו: להיות פחות בולט, פחות רגיש, יותר חזק, יותר מקובל, יותר ״מסתדר״.
כדי להיות מוגן, אני צריך להיות הילד שהסביבה יכולה לשאת.
וזה כבר לא רק: ״כדי להשתייך אני צריך להתאים את עצמי״. זו משוואה בעלת מחיר גבוה יותר:
כדי שלא יפגעו בי, אני צריך להתאים את עצמי.
כשהתאמה עצמית הופכת לאסטרטגיית מוגנות, קשה יותר להבחין בין צמיחה לבין ויתור על חלקים מן העצמי כדי להקטין סכנה.
אבן דומינו 8 — אבל מה אם אני לא מצליחה להשתנות?
הדרישה לכאורה פשוטה: אל תהיה כזה. אל תבכה. אל תיעלב. אל תהיה חלש. תהיה יותר מקובל. תסתדר. תעמוד על שלך. אל תיתן להם.
אבל ילד לא תמיד יודע איך. אולי הוא מנסה. ומנסה שוב. וזה לא עובד.
הוא עדיין מפחד. הוא עדיין נעלב. עדיין לא בוחרים בו. עדיין צוחקים. עדיין אותו ילד חזק ממנו. עדיין הקבוצה שם מחר בבוקר.
ואז השאלה כבר איננה רק ״מה אני צריך לעשות?״ אלא שאלה עמוקה יותר:
האם יש בכלל משהו שאני יכול לעשות שישנה את מה שקורה לי?
כאן מתחיל המעבר מן הסתגלות פעילה אל חוויה אפשרית של חוסר אונים. לא משום שהילד לא ניסה, אלא דווקא משום שניסה שוב ושוב ולא מצא פעולה שמשנה מספיק את המצב.
אבן דומינו 9 — Fight, Flight, Freeze: ומה קורה כשאין דרך יעילה לצאת מן האיום?
כאן אפשר להשתמש ב-Fight / Flight / Freeze בזהירות, כמודל מארגן ולא כטענה שחוסר אונים נלמד הוא ״התגובה הרביעית״ או שלב מכני שמגיע תמיד אחרי שלוש תגובות שנכשלו.
Flight — לברוח
אפשר אולי לברוח מהרגע. לצאת מהחדר, להתרחק מילד מסוים, להסתתר לזמן קצר. אבל אי אפשר באמת לברוח מן הקבוצה.
אני חוזרת אליה לארוחה, למקלחת, ללינה, למחר בבוקר. היא אינה אירוע שממנו יוצאים; היא סביבת החיים.
אין לאן לברוח מן הקבוצה, כי הקבוצה היא סביבת החיים.
Fight — להילחם
אפשר להילחם בילד. אפשר לצעוק, להחזיר, לדחוף, להתנגד. אבל קשה להילחם בקבוצה כולה. ועוד יותר מזה: הקבוצה אינה רק אויב אפשרי. היא גם הבית החברתי שלי, המקום שלי, השייכות שלי.
אני לא יכולה פשוט להילחם בקבוצה, כי הקבוצה היא גם חלק ממי שאני.
לנצח את הקבוצה במחיר של אובדן השייכות אינו בהכרח ניצחון. לפעמים עצם ההתנגדות מגדילה את הסכנה החברתית.
Freeze — לקפוא
אני יכולה להפסיק להגיב. לא להראות. לא לבכות. להיעלם. להיסגר. להפוך את עצמי לפחות נגיש לפגיעה.
אבל הקיפאון אינו בהכרח מפסיק את הכאב או משנה את המציאות החברתית. הוא יכול להפחית חומר שהקבוצה מקבלת ממני, אבל לא בהכרח לשנות את תנאי החיים.
ומכאן נקודת החיבור לחוסר אונים נלמד:
כאשר שוב ושוב הפעולות הזמינות לי אינן משנות את הדבר החשוב — יכולה להיווצר למידה שאין טעם בפעולה.
אבן דומינו 10 — חוסר אונים נלמד: לא ״אני חלש״ אלא ״מה שאני עושה לא משנה״
זה חידוד חשוב. חוסר אונים נלמד אינו צריך להתחיל במחשבה ״אני חסר יכולת״. קודם יכולה להילמד חוויה בסיסית יותר: אין קשר יציב בין מה שאני עושה לבין מה שקורה לי.
• ניסיתי לדבר — לא השתנה.
• ניסיתי לברוח — חזרתי לאותו מקום.
• ניסיתי להילחם — שילמתי מחיר.
• ניסיתי לא להגיב — זה המשיך.
• ניסיתי להשתנות — ועדיין מצאו משהו.
