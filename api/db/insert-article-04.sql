-- A new article 4, ״זה שום דבר״, enters the series. Every article numbered 4 and
-- up moves one place down, slug and order both: article-04 → article-05 …
-- Safe because none of them is published, so no one holds their addresses;
-- one that ever was (published_at set) is not moved, and the shift then fails
-- on its slug and rolls the whole thing back rather than break a public link.
--
-- After this runs, the older seed files that address rows by slug
-- (seed-article-card-*.sql, seed-cards-*.sql) point at the wrong articles.
-- Do not re-run them. Nor renumber-articles-insert-03.sql.
--
-- One transaction. Running it a second time changes nothing: every step is
-- guarded by the new article not existing yet.
--
-- Also: the ״במאמר הבא״ box at the end of article 3 links its title to the
-- new article 4.

BEGIN;

-- 1. Out of the way first: slugs are unique, and shifting in place would
--    collide with the neighbour's slug mid-statement.
UPDATE articles SET slug = 'tmp-' || slug
WHERE slug ~ '^article-\d+$'
  AND substring(slug from '^article-(\d+)$')::int >= 4
  AND published_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM articles WHERE title_lead = '״זה שום דבר״');

-- 2. Each one place down, in slug and in order.
UPDATE articles SET
  slug = 'article-' || lpad((substring(slug from '^tmp-article-(\d+)$')::int + 1)::text, 2, '0'),
  sort_order = sort_order + 1,
  updated_at = now()
WHERE slug ~ '^tmp-article-\d+$';

-- 3. The new article 4, with its working card.
INSERT INTO articles (slug, title_lead, title_topic, sort_order, status, canvas)
SELECT 'article-04',
