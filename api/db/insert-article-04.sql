-- 4. Article 3's teaser: the next article's title becomes a link to it.
UPDATE articles SET
  blocks = (
    SELECT jsonb_agg(
             CASE WHEN b->>'type' = 'fact' AND b->>'title' = 'במאמר הבא'
                  THEN jsonb_set(b, '{body}', to_jsonb(replace(b->>'body',
                         '**״זה שום דבר״**', '[**״זה שום דבר״**](/library/article-04)')))
                  ELSE b END
             ORDER BY ord)
    FROM jsonb_array_elements(blocks) WITH ORDINALITY AS t(b, ord)),
  updated_at = now()
WHERE slug = 'article-03'
  AND position('(/library/article-04)' in blocks::text) = 0;

COMMIT;
